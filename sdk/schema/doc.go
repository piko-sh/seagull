// Package schema lets the generator read its schema from somewhere other than the
// migration files, such as a live database.
//
// By default Seagull builds its schema catalogue by replaying the DDL in the migration
// files. A [SchemaSourcePort] builds the catalogue instead: on every run the generator
// calls its BuildCatalogue, works on a copy of the result, leaves out the migration
// runtime tables and analyses each query against it. Pass a source to the generator with
// seagull.WithSchemaSource; the Migrations field of seagull.Input is then not needed,
// although Queries still is.
//
// The package names what a source works with beside the catalogue it returns, the
// Catalogue of sdk/dialect: [SourceError], [SeverityError] and [SeverityWarning] for the
// diagnostics it reports beside it, and [TypeNormaliserPort], the part of a dialect that
// turns the database's type names into SQL types.
//
// # Providers
//
//   - schema_source_postgres reads a live PostgreSQL, CockroachDB or TimescaleDB database
//     through pg_catalog and information_schema.
//   - schema_source_sqlite reads a live SQLite database through PRAGMA commands.
//
// # Usage
//
//	engine := dialect_engine_sqlite.New()
//	generator, err := seagull.New(engine,
//	    seagull.WithSchemaSource(schema_source_sqlite.New(database, engine)),
//	)
//	if err != nil {
//	    return err
//	}
//	result, err := generator.Generate(ctx, seagull.Input{Queries: queries, Package: "store"})
//
// The caller opens and closes the database; the source only reads from it.
//
// # Writing a source
//
// Any other schema authority, such as a schema registry, a description generated by
// another tool or a cached catalogue, can implement [SchemaSourcePort] itself.
// BuildCatalogue returns a dialect.Catalogue built from the model types sdk/dialect
// names, such as dialect.Table and dialect.NewColumn, with its SQL types normalised
// through the dialect the generator uses. The guide docs/how-to/custom-schema-source.md
// builds one from start to finish.
