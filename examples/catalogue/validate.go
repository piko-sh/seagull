const (
	// licenceMarker is a line every hand-written Go file in an example must carry.
	licenceMarker = "Licensed under the Apache License, Version 2.0"

	// generatedMarker starts every file sgl generates.
	generatedMarker = "// Code generated by sgl. DO NOT EDIT."
)

var (
	// variantDirPattern matches a variant directory's name.
	variantDirPattern = regexp.MustCompile(`^[0-9]{3}_[a-z0-9_]+$`)

	// liveValues lists the allowed example.yaml live values.
	liveValues = []string{"yes", "partial", "no"}

	// testModes maps each example.yaml test mode to the files it needs.
	testModes = map[string][]string{
		"in-process":    {"example.go", "main.go", "main_test.go", "output.txt"},
		"cgo":           {"example.go", "main.go", "main_test.go", "output.txt"},
		"integration":   {"example.go", "main.go", "main_test.go", "output.txt"},
		"transcript":    {"transcript.txt", "transcript_test.go"},
		"generate-only": {"main.go"},
	}

	// cellStatuses lists the allowed cell statuses.
	cellStatuses = []string{StatusVariant, StatusEquivalent, StatusUnsupported, StatusOmitted, StatusBlocked}
)

// projectConfig is the part of a variant's sgl.yaml the checks read.
type projectConfig struct {
	// Databases lists the project's databases; examples have one.
	Databases []struct {
		// Dialect is the database's dialect.
		Dialect string `yaml:"dialect"`

		// Go holds the generator settings.
		Go struct {
			// Driver is the emitter the database uses.
			Driver string `yaml:"driver"`
		} `yaml:"go"`
	} `yaml:"databases"`
}

// checkStructure checks concepts.yaml on its own: numbering, tracks, columns and cells.
//
// Returns []error which lists the problems found.
func (c *Curriculum) checkStructure() []error {
	var problems []error
	if c.Version != 1 {
		problems = append(problems, fmt.Errorf("%s: version %d, want 1", ConceptsFile, c.Version))
	}
	tracks := make(map[string]bool)
	for _, track := range c.Tracks {
		tracks[track.ID] = true
	}
	for _, column := range c.Columns {
		if _, ok := c.Engines[column.Engine]; !ok {
			problems = append(problems, fmt.Errorf("column %s: unknown engine %s", column.ID, column.Engine))
		}
	}
	slugs := make(map[string]bool)
	for index := range c.Concepts {
		concept := &c.Concepts[index]
		problems = append(problems, c.checkConcept(concept, index+1, tracks, slugs)...)
	}
	return problems
}

// checkConcept checks one concept's numbering, fields and cells.
//
// Takes concept (*Concept) which is the concept.
// Takes want (int) which is the number the concept should have.
// Takes tracks (map[string]bool) which holds the known track IDs.
// Takes slugs (map[string]bool) which collects the slugs seen so far.
//
// Returns []error which lists the problems found.
func (c *Curriculum) checkConcept(concept *Concept, want int, tracks, slugs map[string]bool) []error {
	var problems []error
	name := fmt.Sprintf("concept %d %s", concept.Number, concept.Slug)
	if concept.Number != want {
		problems = append(problems, fmt.Errorf("%s: numbered %d, want %d (numbers are contiguous and in order)", name, concept.Number, want))
	}
	if slugs[concept.Slug] {
		problems = append(problems, fmt.Errorf("%s: duplicate slug", name))
	}
	slugs[concept.Slug] = true
	if _, clash := c.Engines[concept.Slug]; clash {
		problems = append(problems, fmt.Errorf("%s: slug equals an engine name, which the website's URLs cannot tell apart", name))
	}
	if !tracks[concept.Track] {
		problems = append(problems, fmt.Errorf("%s: unknown track %q", name, concept.Track))
	}
	if concept.Title == "" || concept.Summary == "" {
		problems = append(problems, fmt.Errorf("%s: needs a title and a summary", name))
	}
	for _, column := range c.Columns {
		_, has := concept.Cells[column.ID]
		inScope := len(concept.Scope) == 0 || slices.Contains(concept.Scope, column.Engine)
		if inScope && !has {
			problems = append(problems, fmt.Errorf("%s: no cell for %s", name, column.ID))
		}
	}
	for columnID, cell := range concept.Cells {
		problems = append(problems, c.checkCell(name, concept, columnID, cell)...)
	}
	return problems
}

// checkCell checks one cell's column, status and references.
//
// Takes name (string) which names the concept in messages.
// Takes concept (*Concept) which is the cell's concept.
// Takes columnID (string) which is the cell's column.
// Takes cell (Cell) which is the cell.
//
// Returns []error which lists the problems found.
func (c *Curriculum) checkCell(name string, concept *Concept, columnID string, cell Cell) []error {
	var problems []error
	column, ok := c.Column(columnID)
	if !ok {
		return append(problems, fmt.Errorf("%s: unknown column %s", name, columnID))
	}
	if len(concept.Scope) > 0 && !slices.Contains(concept.Scope, column.Engine) {
		problems = append(problems, fmt.Errorf("%s: cell %s is outside the concept's scope", name, columnID))
	}
	if !slices.Contains(cellStatuses, cell.Status) {
		problems = append(problems, fmt.Errorf("%s: cell %s has status %q", name, columnID, cell.Status))
	}
	switch cell.Status {
	case StatusEquivalent:
		twin, found := concept.Cells[cell.Twin]
		if !found || twin.Status != StatusVariant {
			problems = append(problems, fmt.Errorf("%s: cell %s is equivalent to %q, which has no variant", name, columnID, cell.Twin))
		}
	case StatusUnsupported, StatusBlocked:
		if cell.Reason == "" {
			problems = append(problems, fmt.Errorf("%s: cell %s needs a reason", name, columnID))
		}
	}
	if cell.See != 0 && (cell.See < 1 || cell.See > len(c.Concepts)) {
		problems = append(problems, fmt.Errorf("%s: cell %s refers to concept %d, which does not exist", name, columnID, cell.See))
	}
	return problems
}

// checkDirectories checks that every variant cell has a matching directory and that every
// variant directory belongs to a cell.
//
// Takes examplesDirectory (string) which is the examples directory.
//
// Returns []error which lists the problems found.
func (c *Curriculum) checkDirectories(examplesDirectory string) []error {
	var problems []error
	expected := c.VariantDirectories()
	for relative, ref := range expected {
		directory := filepath.Join(examplesDirectory, relative)
		if !isVariantDirectory(directory) {
			problems = append(problems, fmt.Errorf("%s: missing directory %s", ref, relative))
			continue
		}
		problems = append(problems, c.checkVariant(directory, ref)...)
	}
	return append(problems, c.checkUnnamedDirectories(examplesDirectory, expected)...)
}

// checkUnnamedDirectories finds variant directories in the examples modules that no
// concept cell names.
//
// Takes examplesDirectory (string) which is the examples directory.
// Takes expected (map[string]VariantRef) which holds the directories the cells name.
//
// Returns []error which lists the problems found.
func (c *Curriculum) checkUnnamedDirectories(examplesDirectory string, expected map[string]VariantRef) []error {
	var problems []error
	for _, module := range c.modules() {
		entries, err := os.ReadDir(filepath.Join(examplesDirectory, module))
		if err != nil {
			continue
		}
		for _, entry := range entries {
			if !entry.IsDir() || !variantDirPattern.MatchString(entry.Name()) {
				continue
			}
			relative := filepath.Join(module, entry.Name())
			if _, known := expected[relative]; !known {
				problems = append(problems, fmt.Errorf("%s: no concept cell names this directory", relative))
			}
		}
	}
	return problems
}

// modules lists every examples module the curriculum uses.
//
// Returns []string which holds the module directory names.
func (c *Curriculum) modules() []string {
	var modules []string
	for _, engine := range c.Engines {
		if !slices.Contains(modules, engine.Module) {
			modules = append(modules, engine.Module)
		}
	}
	for index := range c.Concepts {
		if module := c.Concepts[index].Module; module != "" && !slices.Contains(modules, module) {
			modules = append(modules, module)
		}
	}
	slices.Sort(modules)
	return modules
}

// checkVariant checks one variant directory against its cell.
//
// Takes directory (string) which is the variant directory.
// Takes ref (VariantRef) which is the variant's concept and column.
//
// Returns []error which lists the problems found.
func (c *Curriculum) checkVariant(directory string, ref VariantRef) []error {
	var problems []error
	variant, err := LoadVariant(directory)
	if err != nil {
		return append(problems, fmt.Errorf("%s: %w", ref, err))
	}
	problems = append(problems, checkVariantFields(ref, variant)...)
	problems = append(problems, checkFiles(directory, ref, variant)...)
	problems = append(problems, c.checkConfig(directory, ref, variant)...)
	problems = append(problems, checkEntry(directory, ref, variant)...)
	problems = append(problems, checkLicences(directory, ref)...)
	return problems
}

// checkConfig checks that sgl.yaml's dialect and driver match the variant's column.
//
// Takes directory (string) which is the variant directory.
// Takes ref (VariantRef) which identifies the variant.
// Takes variant (*Variant) which is the manifest.
//
// Returns []error which lists the problems found.
func (c *Curriculum) checkConfig(directory string, ref VariantRef, _ *Variant) []error {
	data, err := readIn(directory, configFile)
	if err != nil {
		return nil
	}
	// projectConfig reads only the keys this check compares, so the other keys an sgl.yaml
	// holds are expected here; sgl itself refuses an unknown key, or a second document,
	// whenever it loads the file.
	var config projectConfig
	if err := yaml.Unmarshal(data, &config); err != nil {
		return []error{fmt.Errorf("%s: sgl.yaml: %w", ref, err)}
	}
	if len(config.Databases) == 0 {
		return []error{fmt.Errorf("%s: sgl.yaml has no databases", ref)}
	}
	var problems []error
	database := config.Databases[0]
	if want := c.Engines[ref.Column.Engine].Dialect; database.Dialect != want {
		problems = append(problems, fmt.Errorf("%s: sgl.yaml dialect %q, want %q", ref, database.Dialect, want))
	}
	driver := database.Go.Driver
	if driver == "" {
		driver = "database/sql"
	}
	if driver != ref.Column.Driver {
		problems = append(problems, fmt.Errorf("%s: sgl.yaml driver %q, want %q", ref, driver, ref.Column.Driver))
	}
	return problems
}

// Validate checks the curriculum in examplesDirectory against the variant directories.
//
// Takes examplesDirectory (string) which is the examples directory.
//
// Returns error which joins every problem found, or nil.
func Validate(examplesDirectory string) error {
	curriculum, err := Load(examplesDirectory)
	if err != nil {
		return err
	}
	problems := curriculum.checkStructure()
	problems = append(problems, curriculum.checkDirectories(examplesDirectory)...)
	problems = append(problems, curriculum.checkDocs(examplesDirectory)...)
	return errors.Join(problems...)
}

// checkVariantFields checks example.yaml's enumerated fields.
//
// Takes ref (VariantRef) which identifies the variant.
// Takes variant (*Variant) which is the manifest.
//
// Returns []error which lists the problems found.
func checkVariantFields(ref VariantRef, variant *Variant) []error {
	var problems []error
	if variant.Summary == "" {
		problems = append(problems, fmt.Errorf("%s: example.yaml needs a summary", ref))
	}
	if !slices.Contains(liveValues, variant.Live) {
		problems = append(problems, fmt.Errorf("%s: live %q, want one of %v", ref, variant.Live, liveValues))
	}
	if variant.Live == "yes" && ref.Column.Engine != "sqlite" {
		problems = append(problems, fmt.Errorf("%s: only SQLite variants can run fully in the browser", ref))
	}
	if _, ok := testModes[variant.Test]; !ok {
		problems = append(problems, fmt.Errorf("%s: unknown test mode %q", ref, variant.Test))
	}
	return problems
}

// checkFiles checks that the files the variant's test mode needs exist.
//
// Takes directory (string) which is the variant directory.
// Takes ref (VariantRef) which identifies the variant.
// Takes variant (*Variant) which is the manifest.
//
// Returns []error which lists the problems found.
func checkFiles(directory string, ref VariantRef, variant *Variant) []error {
	var problems []error
	required := append([]string{"sgl.yaml"}, testModes[variant.Test]...)
	for _, name := range required {
		if _, err := os.Stat(filepath.Join(directory, name)); err != nil {
			problems = append(problems, fmt.Errorf("%s: missing %s", ref, name))
		}
	}
	return problems
}

// checkEntry checks that the entry query is declared in its file.
//
// Takes directory (string) which is the variant directory.
// Takes ref (VariantRef) which identifies the variant.
// Takes variant (*Variant) which is the manifest.
//
// Returns []error which lists the problems found.
func checkEntry(directory string, ref VariantRef, variant *Variant) []error {
	if variant.Entry.File == "" {
		return nil
	}
	data, err := readIn(directory, filepath.FromSlash(variant.Entry.File))
	if err != nil {
		return []error{fmt.Errorf("%s: entry file %s: %w", ref, variant.Entry.File, err)}
	}
	if variant.Entry.Query != "" && !strings.Contains(string(data), "sgl.query("+variant.Entry.Query) {
		return []error{fmt.Errorf("%s: entry query %s is not declared in %s", ref, variant.Entry.Query, variant.Entry.File)}
	}
	return nil
}

// checkLicences checks that every hand-written Go file carries the licence header. It
// walks the variant through an os.Root, so it reads nothing outside the directory.
//
// Takes directory (string) which is the variant directory.
// Takes ref (VariantRef) which identifies the variant.
//
// Returns []error which lists the problems found.
func checkLicences(directory string, ref VariantRef) []error {
	root, err := os.OpenRoot(directory)
	if err != nil {
		return []error{fmt.Errorf("%s: %w", ref, err)}
	}
	defer func() { _ = root.Close() }()
	files := root.FS()
	var problems []error
	walkErr := fs.WalkDir(files, ".", func(name string, entry fs.DirEntry, err error) error {
		if err != nil || entry.IsDir() || !strings.HasSuffix(name, ".go") {
			return err
		}
		data, readErr := fs.ReadFile(files, name)
		if readErr != nil {
			return readErr
		}
		text := string(data)
		if strings.HasPrefix(text, generatedMarker) {
			return nil
		}
		if !strings.Contains(text, licenceMarker) {
			problems = append(problems, fmt.Errorf("%s: %s has no licence header", ref, filepath.FromSlash(name)))
		}
		return nil
	})
	if walkErr != nil {
		problems = append(problems, fmt.Errorf("%s: checking licences: %w", ref, walkErr))
	}
	return problems
}

// isVariantDirectory reports whether directory exists and holds an example.yaml, so a
// variant still being written is not mistaken for a finished one.
//
// Takes directory (string) which is the variant directory.
//
// Returns bool which is true when the variant has its manifest.
func isVariantDirectory(directory string) bool {
	info, err := os.Stat(filepath.Join(directory, VariantFile))
	return err == nil && !info.IsDir()
}
