CREATE TABLE boats (
    id   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT   NOT NULL,
    gear JSONB  NOT NULL DEFAULT '{}'
);

CREATE TABLE landings (
    id        BIGINT   GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    boat_id   BIGINT   NOT NULL REFERENCES boats (id),
    species   TEXT     NOT NULL,
    kilos     INTEGER  NOT NULL,
    landed_on DATE     NOT NULL,
    notes     TEXT     NOT NULL,
    search    TSVECTOR GENERATED ALWAYS AS (to_tsvector('english', species || ' ' || notes)) STORED
);

CREATE INDEX landings_search_idx ON landings USING GIN (search);

CREATE TABLE landing_archive (
    id        BIGINT  PRIMARY KEY,
    boat_id   BIGINT  NOT NULL REFERENCES boats (id),
    species   TEXT    NOT NULL,
    kilos     INTEGER NOT NULL,
    landed_on DATE    NOT NULL
);
