CREATE TABLE sightings (
    id      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    species TEXT   NOT NULL,
    place   TEXT   NOT NULL
);

CREATE FUNCTION sighting_label(species TEXT, place TEXT) RETURNS TEXT
LANGUAGE sql IMMUTABLE STRICT
AS $$ SELECT species || ' at ' || place $$;

CREATE FUNCTION log_sighting(new_species TEXT, new_place TEXT) RETURNS BIGINT
LANGUAGE plpgsql VOLATILE
AS $$
DECLARE
    new_id BIGINT;
BEGIN
    INSERT INTO sightings (species, place) VALUES (new_species, new_place) RETURNING id INTO new_id;
    RETURN new_id;
END;
$$;
