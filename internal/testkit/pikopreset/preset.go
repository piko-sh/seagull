package pikopreset

import (
	"seagull.sh/seagull/internal/app"
	"seagull.sh/seagull/internal/dialect"
	"seagull.sh/seagull/internal/dialect/sqlite"
)

const (
	// Namespace is the prefix of Piko's persisted migration and seed objects.
	Namespace = "piko"

	// prefix is Piko's directive, helper and error prefix.
	prefix = "piko"

	// header is the generated-file header Piko writes.
	header = "// Code generated by Piko. DO NOT EDIT."

	// mathsPackage is the import path of Piko's precise numeric types.
	mathsPackage = "piko.sh/piko/wdk/maths"

	// jsonPackage is the import path of Piko's JSON column type and scan adapter.
	jsonPackage = "piko.sh/piko/wdk/db/dbjson"

	// sqliteInteger is the SQLite type Piko reads as a 32-bit integer.
	sqliteInteger = "integer"

	// goInt32 is the Go type Piko reads a SQLite integer into.
	goInt32 = "int32"
)

// Preset returns the settings used for byte-for-byte Piko compatibility checks.
//
// Returns app.Preset which is a fresh copy of Piko's preset.
func Preset() app.Preset {
	decimal := app.Slot{
		NotNull:  app.GoType{Composite: nil, Package: mathsPackage, Name: "Decimal"},
		Nullable: app.GoType{Composite: nil, Package: mathsPackage, Name: "*Decimal"},
	}
	document := app.GoType{Composite: nil, Package: jsonPackage, Name: "JSON"}
	return app.Preset{
		Directives: app.Directives{
			Canonical:        prefix,
			Aliases:          nil,
			Foreign:          nil,
			RequireCanonical: false,
		},
		Header:               header,
		HelperPrefix:         prefix,
		ErrorPrefix:          prefix,
		SQLConstantSuffix:    "",
		SQLConstantLowerCase: true,
		NonNullElements:      true,
		KeepStars:            true,
		StructTags:           nil,
		Interface:            app.Interface{Enabled: false, Name: ""},
		JSONTags:             app.JSONTags{Case: app.JSONCaseAsWritten, Omit: false, OmitEmpty: false},
		EmptySlices:          false,
		DocComments:          false,
		ReuseModels:          false,
		ModernIdioms:         false,
		WrapErrors:           false,
		QueryNames: app.QueryNames{
			Enabled:  true,
			File:     "otel.go",
			Function: "QueryNameResolver",
		},
		Types: app.TypeSlots{
			Decimal: decimal,
			Money:   decimal,
			BigInt: app.Slot{
				NotNull:  app.GoType{Composite: nil, Package: mathsPackage, Name: "BigInt"},
				Nullable: app.GoType{Composite: nil, Package: mathsPackage, Name: "*BigInt"},
			},
			JSON: app.Slot{NotNull: document, Nullable: document},
			JSONScanInto: app.Slot{
				NotNull:  app.GoType{Composite: nil, Package: jsonPackage, Name: "ScanInto"},
				Nullable: app.GoType{Composite: nil, Package: "", Name: ""},
			},
			Interval:  app.Slot{},
			TimeOfDay: app.Slot{},
			IPAddress: app.Slot{},
			Enum: app.Slot{
				NotNull:  app.GoType{Composite: nil, Package: "", Name: "string"},
				Nullable: app.GoType{Composite: nil, Package: "", Name: "*string"},
			},
			Map:    app.Slot{},
			Struct: app.Slot{},
		},
	}
}

// TypeOverrides returns the type overrides Piko generates with for a dialect, which a
// preset's slots cannot express since they name an engine's type: for the SQLite family,
// Piko reads INTEGER as int32, or *int32 when nullable, where Seagull reads it as the
// 64-bit integer it is.
//
// Takes info (*dialect.Info) which describes the dialect. TypeOverrides does not change
// it.
//
// Returns []app.TypeOverride which holds the overrides, or nil for a dialect that needs
// none.
func TypeOverrides(info *dialect.Info) []app.TypeOverride {
	if info.Family != sqlite.Family {
		return nil
	}
	return []app.TypeOverride{{SQLTypeName: sqliteInteger, Column: "", GoPackage: "", GoName: goInt32, NonNullElements: nil, StructTags: nil}}
}
