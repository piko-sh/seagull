const (
	// snapshotHeader is the comment that opens every golden file, above the first entry.
	snapshotHeader = "Seagull Public API Surface\n\n" +
		"This file is auto-generated by `go test -update-api`. DO NOT EDIT.\n" +
		"It is a snapshot of the public API to prevent unintentional breaking changes."

	// missingGoldenMessage is the failure for a golden file that has not been recorded.
	missingGoldenMessage = "API snapshot %s does not exist; record it with go test -update-api"

	// goldenFileMode is the permission a newly recorded golden file is created with.
	goldenFileMode fs.FileMode = 0o644

	// yamlIndent is how many spaces indent each nested level of the golden file.
	yamlIndent = 2

	// nilSignature is what a nil entry, or a nil type, renders as.
	nilSignature = "nil"
)

// Surface is the exported API of a package. Each key is a member's exported name, such as
// "Options", and each value stands for that member: a zero struct such as Options{}, a
// function such as New, a constant, or a nil pointer to an interface such as
// (*ObserverPort)(nil).
type Surface map[string]any

// Check compares the snapshot of surface with the golden file at goldenFile and fails the
// test when they differ, so a change to a package's exported API cannot pass unnoticed.
//
// Run the test with -update-api to record the snapshot into goldenFile first; the
// comparison then passes and the change shows in the file's diff for review.
//
// Takes t (*testing.T) which is the test that fails on a difference.
// Takes surface (Surface) which lists the package's exported members.
// Takes goldenFile (string) which is the path of the golden file, relative to the test's
// package directory, such as facade_test.golden.yaml.
func Check(t *testing.T, surface Surface, goldenFile string) {
	t.Helper()

	check(t, surface, goldenFile, *updateAPI)
}

// check is Check with the recording decided by the caller rather than the flag.
//
// Takes t (testing.TB) which is the test that fails on a difference.
// Takes surface (Surface) which lists the package's exported members.
// Takes goldenFile (string) which is the path of the golden file.
// Takes record (bool) which writes the snapshot into goldenFile before comparing.
func check(t testing.TB, surface Surface, goldenFile string, record bool) {
	t.Helper()

	snapshot, err := renderSnapshot(surface)
	require.NoError(t, err, "rendering the API snapshot")

	mode := safedisk.ModeReadOnly
	if record {
		mode = safedisk.ModeReadWrite
	}
	sandbox, err := safedisk.NewSandbox(filepath.Dir(goldenFile), mode)
	if errors.Is(err, fs.ErrNotExist) {
		t.Fatalf(missingGoldenMessage, goldenFile)
	}
	require.NoError(t, err, "opening the directory of %s", goldenFile)
	defer closeSandbox(t, sandbox, goldenFile)

	goldenName := filepath.Base(goldenFile)
	if record {
		require.NoError(t, sandbox.WriteFile(goldenName, snapshot, goldenFileMode), "recording %s", goldenFile)
		t.Logf("API snapshot recorded: %s", goldenFile)
	}

	expected, err := sandbox.ReadFile(goldenName)
	if errors.Is(err, fs.ErrNotExist) {
		t.Fatalf(missingGoldenMessage, goldenFile)
	}
	require.NoError(t, err, "reading %s", goldenFile)
	require.Equal(t, string(expected), string(snapshot),
		"the API surface no longer matches %s; if the change is intended, record it again with go test -update-api and review the diff", goldenFile)
}

// closeSandbox closes the sandbox around a golden file. A failure only goes to the test
// log, since the comparison has already settled the result.
//
// Takes t (testing.TB) which receives the log line.
// Takes sandbox (safedisk.Sandbox) which is rooted at the golden file's directory.
// Takes goldenFile (string) which names the golden file in the log line.
func closeSandbox(t testing.TB, sandbox safedisk.Sandbox, goldenFile string) {
	t.Helper()

	if err := sandbox.Close(); err != nil {
		t.Logf("closing the directory of %s: %v", goldenFile, err)
	}
}

// renderSnapshot encodes the snapshot of a surface as the YAML a golden file holds.
//
// Takes surface (Surface) which lists the package's exported members.
//
// Returns []byte which is the YAML document.
// Returns error when the document cannot be encoded.
func renderSnapshot(surface Surface) ([]byte, error) {
	var buffer bytes.Buffer
	encoder := yaml.NewEncoder(&buffer)
	encoder.SetIndent(yamlIndent)
	if err := encoder.Encode(generateAPISnapshotYAML(surface)); err != nil {
		return nil, fmt.Errorf("encoding the API snapshot: %w", err)
	}
	if err := encoder.Close(); err != nil {
		return nil, fmt.Errorf("closing the API snapshot encoder: %w", err)
	}
	return buffer.Bytes(), nil
}

// generateAPISnapshotYAML builds the YAML node tree of a surface: a mapping from each
// name, in sorted order and marked with its kind, to the member's signature. A signature
// that spans several lines is written as a literal block.
//
// Takes surface (Surface) which lists the package's exported members.
//
// Returns *yaml.Node which is the root mapping, headed by the golden file's comment.
func generateAPISnapshotYAML(surface Surface) *yaml.Node {
	rootNode := &yaml.Node{
		Kind:        yaml.MappingNode,
		HeadComment: snapshotHeader,
	}

	for _, name := range slices.Sorted(maps.Keys(surface)) {
		entity := surface[name]
		signature := generateSignature(entity)

		keyNode := &yaml.Node{
			Kind:        yaml.ScalarNode,
			Value:       name,
			LineComment: "# Kind: " + getEntityType(entity),
		}

		valueNode := &yaml.Node{
			Kind:  yaml.ScalarNode,
			Value: signature,
		}
		if strings.Contains(signature, "\n") {
			valueNode.Style = yaml.LiteralStyle
		}

		rootNode.Content = append(rootNode.Content, keyNode, valueNode)
	}

	return rootNode
}

// generateSignature renders one member of a surface. A struct lists its fields and
// methods, a nil pointer to an interface lists the interface's methods, a function shows
// its signature, and any other value shows its type.
//
// Takes entity (any) which is the value that stands for the member.
//
// Returns string which is the signature, or "nil" for a nil entity.
func generateSignature(entity any) string {
	if entity == nil {
		return nilSignature
	}

	entityType := reflect.TypeOf(entity)
	if entityType.Kind() == reflect.Pointer && entityType.Elem().Kind() == reflect.Interface {
		entityType = entityType.Elem()
	}

	switch entityType.Kind() {
	case reflect.Struct:
		return generateStructSignature(entityType, reflect.PointerTo(entityType))
	case reflect.Interface:
		return generateInterfaceSignature(entityType)
	case reflect.Func:
		return formatType(entityType)
	default:
		return entityType.String()
	}
}

// generateStructSignature renders a struct type as its exported fields, a count of its
// unexported fields, and its exported methods.
//
// Takes structType (reflect.Type) which is the struct type.
// Takes ptrToStructType (reflect.Type) which is a pointer to it, whose method set also
// holds the methods declared on a pointer receiver.
//
// Returns string which is the struct's signature as a multi-line block.
func generateStructSignature(structType, ptrToStructType reflect.Type) string {
	var builder strings.Builder
	builder.WriteString("struct {\n")
	writeStructFields(&builder, structType)
	writeStructMethods(&builder, ptrToStructType, structType.NumField() > 0)
	builder.WriteString("}")
	return builder.String()
}

// writeStructFields writes each exported field of a struct type, then the number of
// unexported fields when there are any.
//
// Takes builder (*strings.Builder) which receives the lines.
// Takes structType (reflect.Type) which is the struct type.
func writeStructFields(builder *strings.Builder, structType reflect.Type) {
	exportedFieldCount := 0
	for field := range structType.Fields() {
		if !field.IsExported() {
			continue
		}
		exportedFieldCount++
		fmt.Fprintf(builder, "    // Field\n    %s %s\n", field.Name, formatType(field.Type))
	}

	unexportedFieldCount := structType.NumField() - exportedFieldCount
	if unexportedFieldCount == 0 {
		return
	}
	if exportedFieldCount > 0 {
		builder.WriteString("\n")
	}
	fmt.Fprintf(builder, "    // (+%d unexported fields)\n", unexportedFieldCount)
}

// writeStructMethods writes each exported method in the method set of a pointer to a
// struct type, after a blank line when the struct has fields.
//
// Takes builder (*strings.Builder) which receives the lines.
// Takes ptrToStructType (reflect.Type) which is the pointer to the struct type.
// Takes hasFields (bool) which is true when the struct has any field.
func writeStructMethods(builder *strings.Builder, ptrToStructType reflect.Type, hasFields bool) {
	separated := !hasFields
	for method := range ptrToStructType.Methods() {
		if !method.IsExported() {
			continue
		}
		if !separated {
			builder.WriteString("\n")
			separated = true
		}
		fmt.Fprintf(builder, "    // Method\n    %s%s\n", method.Name, formatMethod(method.Type))
	}
}

// generateInterfaceSignature renders an interface type as its methods, one per line.
//
// Takes interfaceType (reflect.Type) which is the interface type.
//
// Returns string which is the interface's signature as a multi-line block.
func generateInterfaceSignature(interfaceType reflect.Type) string {
	var builder strings.Builder
	builder.WriteString("interface {\n")
	for method := range interfaceType.Methods() {
		fmt.Fprintf(&builder, "    %s%s\n", method.Name, formatFunction(method.Type))
	}
	builder.WriteString("}")
	return builder.String()
}

// formatType renders a type, writing a function type as func and its signature.
//
// Takes reflectType (reflect.Type) which is the type to render.
//
// Returns string which is the rendered type, or "nil" for a nil type.
func formatType(reflectType reflect.Type) string {
	if reflectType == nil {
		return nilSignature
	}
	if reflectType.Kind() == reflect.Func {
		return "func" + formatFunction(reflectType)
	}
	return reflectType.String()
}

// formatFunction renders the parameters and results of a function type.
//
// Takes functionType (reflect.Type) which is the type to render.
//
// Returns string which is the signature, such as "(int, string) error", or the type's own
// name when it is not a function type.
func formatFunction(functionType reflect.Type) string {
	if functionType.Kind() != reflect.Func {
		return functionType.String()
	}

	parameters := make([]string, 0, functionType.NumIn())
	for parameter := range functionType.Ins() {
		parameters = append(parameters, formatType(parameter))
	}

	return formatMethodSignature(parameters, formatResults(functionType), functionType.IsVariadic())
}

// formatMethod renders the parameters and results of a method taken from a type's method
// set, leaving out the receiver that reflection lists as the first parameter.
//
// Takes methodType (reflect.Type) which is the method's function type.
//
// Returns string which is the signature without the receiver.
func formatMethod(methodType reflect.Type) string {
	parameters := make([]string, 0, methodType.NumIn())
	for index := 1; index < methodType.NumIn(); index++ {
		parameters = append(parameters, formatType(methodType.In(index)))
	}

	return formatMethodSignature(parameters, formatResults(methodType), methodType.IsVariadic())
}

// formatResults renders each result type of a function type.
//
// Takes functionType (reflect.Type) which is the function type.
//
// Returns []string which holds one rendered type per result.
func formatResults(functionType reflect.Type) []string {
	results := make([]string, 0, functionType.NumOut())
	for result := range functionType.Outs() {
		results = append(results, formatType(result))
	}
	return results
}

// formatMethodSignature joins rendered parameter and result types into a signature. A
// variadic final parameter is written with an ellipsis, and several results are wrapped
// in parentheses.
//
// Takes parameters ([]string) which holds the rendered parameter types.
// Takes results ([]string) which holds the rendered result types.
// Takes isVariadic (bool) which is true when the final parameter is variadic.
//
// Returns string which is the signature, such as "(int, string) error".
func formatMethodSignature(parameters, results []string, isVariadic bool) string {
	rendered := parameters
	if isVariadic && len(parameters) > 0 {
		rendered = slices.Clone(parameters)
		last := len(rendered) - 1
		rendered[last] = "..." + strings.TrimPrefix(rendered[last], "[]")
	}

	parameterList := strings.Join(rendered, ", ")
	switch len(results) {
	case 0:
		return fmt.Sprintf("(%s)", parameterList)
	case 1:
		return fmt.Sprintf("(%s) %s", parameterList, results[0])
	default:
		return fmt.Sprintf("(%s) (%s)", parameterList, strings.Join(results, ", "))
	}
}

// getEntityType names the kind of member a surface entry stands for.
//
// Takes entity (any) which is the value that stands for the member.
//
// Returns string which is "Nil", "Interface" for a nil pointer to an interface, "Func",
// "Struct", or "Type" for anything else.
func getEntityType(entity any) string {
	if entity == nil {
		return "Nil"
	}

	entityType := reflect.TypeOf(entity)
	if entityType.Kind() == reflect.Pointer && entityType.Elem().Kind() == reflect.Interface {
		return "Interface"
	}

	switch entityType.Kind() {
	case reflect.Func:
		return "Func"
	case reflect.Struct:
		return "Struct"
	default:
		return "Type"
	}
}
