func writeFixture(t *testing.T, directory, name, content string) {
	t.Helper()
	require.NoError(t, os.WriteFile(filepath.Join(directory, name), []byte(content), 0o600))
}

func TestWriteCreatesDirectoryAndWritesFiles(t *testing.T) {
	t.Parallel()

	directory := filepath.Join(t.TempDir(), "nested", "store")
	files := []sqlmodel.GeneratedFile{
		{Name: "models.go", Content: []byte(testHeader + "\n\npackage store\n")},
		{Name: "empty.go", Content: nil},
	}

	require.NoError(t, Write(directory, files, Options{Header: testHeader, Prune: true}))

	content, err := os.ReadFile(filepath.Join(directory, "models.go"))
	require.NoError(t, err)
	assert.Equal(t, string(files[0].Content), string(content))
	assert.NoFileExists(t, filepath.Join(directory, "empty.go"))
}

func TestWritePrunesOnlyStaleGeneratedFiles(t *testing.T) {
	t.Parallel()

	legacy := "// Code generated by legacy. DO NOT EDIT."
	directory := t.TempDir()
	writeFixture(t, directory, "stale.sql.go", testHeader+"\n\npackage store\n")
	writeFixture(t, directory, "legacy.sql.go", legacy+"\n\npackage store\n")
	writeFixture(t, directory, "handwritten.go", "package store\n")
	writeFixture(t, directory, "foreign.go", "// Code generated by other. DO NOT EDIT.\n\npackage store\n")
	files := []sqlmodel.GeneratedFile{{Name: "models.go", Content: []byte(testHeader + "\n\npackage store\n")}}

	require.NoError(t, Write(directory, files, Options{Header: testHeader, LegacyHeaders: []string{legacy}, Prune: true}))

	assert.FileExists(t, filepath.Join(directory, "models.go"))
	assert.NoFileExists(t, filepath.Join(directory, "stale.sql.go"))
	assert.NoFileExists(t, filepath.Join(directory, "legacy.sql.go"))
	assert.FileExists(t, filepath.Join(directory, "handwritten.go"))
	assert.FileExists(t, filepath.Join(directory, "foreign.go"))
}

func TestWriteWithoutPruneKeepsStaleFiles(t *testing.T) {
	t.Parallel()

	directory := t.TempDir()
	writeFixture(t, directory, "stale.sql.go", testHeader+"\n\npackage store\n")

	require.NoError(t, Write(directory, nil, Options{Header: testHeader, Prune: false}))

	assert.FileExists(t, filepath.Join(directory, "stale.sql.go"))
}

func TestWriteAppliesPermissions(t *testing.T) {
	t.Parallel()
	if runtime.GOOS == "windows" {
		t.Skip("POSIX permissions")
	}

	directory := t.TempDir()
	files := []sqlmodel.GeneratedFile{{Name: "models.go", Content: []byte("package store\n")}}

	require.NoError(t, Write(directory, files, Options{Permissions: 0o600}))
	info, err := os.Stat(filepath.Join(directory, "models.go"))
	require.NoError(t, err)
	assert.Equal(t, os.FileMode(0o600), info.Mode().Perm())

	require.NoError(t, Write(directory, files, Options{}))
	info, err = os.Stat(filepath.Join(directory, "models.go"))
	require.NoError(t, err)
	assert.Equal(t, DefaultPermissions, info.Mode().Perm())
}

func TestWriteLeavesAFileThatAlreadyHoldsItsContentAlone(t *testing.T) {
	t.Parallel()
	if runtime.GOOS == "windows" {
		t.Skip("POSIX permissions")
	}

	written := []sqlmodel.GeneratedFile{{Name: "models.go", Content: []byte("package store\n")}}
	past := time.Date(2001, time.February, 3, 4, 5, 6, 0, time.UTC)
	testCases := []struct {
		name      string
		files     []sqlmodel.GeneratedFile
		options   Options
		rewritten bool
	}{
		{name: "the same content and permission", files: written, options: Options{}, rewritten: false},
		{name: "other content", files: []sqlmodel.GeneratedFile{{Name: "models.go", Content: []byte("package shop\n")}}, options: Options{}, rewritten: true},
		{name: "the same content of another length", files: []sqlmodel.GeneratedFile{{Name: "models.go", Content: []byte("package store\n\n")}}, options: Options{}, rewritten: true},
		{name: "another permission", files: written, options: Options{Permissions: 0o600}, rewritten: true},
	}
	for _, testCase := range testCases {
		t.Run(testCase.name, func(t *testing.T) {
			t.Parallel()
			directory := t.TempDir()
			path := filepath.Join(directory, "models.go")
			require.NoError(t, Write(directory, written, Options{}))
			require.NoError(t, os.Chtimes(path, past, past))

			require.NoError(t, Write(directory, testCase.files, testCase.options))

			info, err := os.Stat(path)
			require.NoError(t, err)
			require.Equal(t, testCase.rewritten, !info.ModTime().Equal(past))
			content, err := os.ReadFile(path)
			require.NoError(t, err)
			require.Equal(t, string(testCase.files[0].Content), string(content))
		})
	}
}

func TestWriteRejectsInvalidInput(t *testing.T) {
	t.Parallel()

	tests := []struct {
		name      string
		directory string
		fileName  string
	}{
		{name: "empty directory", directory: "", fileName: "models.go"},
		{name: "empty name", directory: t.TempDir(), fileName: ""},
		{name: "dot", directory: t.TempDir(), fileName: "."},
		{name: "parent", directory: t.TempDir(), fileName: ".."},
		{name: "nested path", directory: t.TempDir(), fileName: "sub/models.go"},
		{name: "backslash", directory: t.TempDir(), fileName: `sub\models.go`},
		{name: "absolute", directory: t.TempDir(), fileName: "/etc/models.go"},
	}
	for _, testCase := range tests {
		t.Run(testCase.name, func(t *testing.T) {
			t.Parallel()

			err := Write(testCase.directory, []sqlmodel.GeneratedFile{{Name: testCase.fileName, Content: []byte("x")}}, Options{})
			require.ErrorIs(t, err, fault.ErrInvalidConfig)
		})
	}
}

func TestWriteLeavesALinkThatEscapesTheOutputDirectoryAlone(t *testing.T) {
	t.Parallel()

	outside := filepath.Join(t.TempDir(), "elsewhere.go")
	require.NoError(t, os.WriteFile(outside, []byte(testHeader+"\n\npackage elsewhere\n"), 0o600))
	directory := t.TempDir()
	link := filepath.Join(directory, "linked.sql.go")
	if err := os.Symlink(outside, link); err != nil {
		t.Skipf("symbolic links are not available here: %v", err)
	}

	err := Write(directory, []sqlmodel.GeneratedFile{{Name: "models.go", Content: []byte(testHeader + "\n\npackage db\n")}},
		Options{Header: testHeader, Prune: true})
	require.NoError(t, err)
	_, err = os.Lstat(link)
	require.NoError(t, err, "a link is never pruned")
	assert.FileExists(t, outside)
}
