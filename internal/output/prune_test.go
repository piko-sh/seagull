const testHeader = "// Code generated by sgl. DO NOT EDIT."

type fakeDirEntry struct {
	name  string
	isDir bool
	mode  fs.FileMode
}

func (entry fakeDirEntry) Name() string         { return entry.name }
func (entry fakeDirEntry) IsDir() bool          { return entry.isDir }
func (entry fakeDirEntry) Type() fs.FileMode    { return entry.mode }
func (fakeDirEntry) Info() (fs.FileInfo, error) { return nil, nil }

type fakeFileHandle struct {
	safedisk.FileHandle
	reader  *bytes.Reader
	readErr error
}

func (handle *fakeFileHandle) Read(destination []byte) (int, error) {
	if handle.readErr != nil {
		return 0, handle.readErr
	}
	return handle.reader.Read(destination)
}

func (*fakeFileHandle) Close() error { return nil }

type fakeOutputDirectory struct {
	files        map[string][]byte
	directories  map[string]bool
	modes        map[string]fs.FileMode
	opened       []string
	openErrors   map[string]error
	readErrors   map[string]error
	removeErrors map[string]error
	readDirErr   error
}

func (directory *fakeOutputDirectory) ReadDir(string) ([]fs.DirEntry, error) {
	if directory.readDirErr != nil {
		return nil, directory.readDirErr
	}
	entries := make([]fs.DirEntry, 0, len(directory.files))
	for name := range directory.files {
		entries = append(entries, fakeDirEntry{name: name, isDir: directory.directories[name], mode: directory.modes[name]})
	}
	return entries, nil
}

func (directory *fakeOutputDirectory) Open(name string) (safedisk.FileHandle, error) {
	directory.opened = append(directory.opened, name)
	if err := directory.openErrors[name]; err != nil {
		return nil, err
	}
	if err := directory.readErrors[name]; err != nil {
		return &fakeFileHandle{readErr: err}, nil
	}
	content, ok := directory.files[name]
	if !ok {
		return nil, fs.ErrNotExist
	}
	return &fakeFileHandle{reader: bytes.NewReader(content)}, nil
}

func (directory *fakeOutputDirectory) Remove(name string) error {
	if err := directory.removeErrors[name]; err != nil {
		return err
	}
	delete(directory.files, name)
	return nil
}

func TestPruneStaleGeneratedFilesHonoursLegacyHeaders(t *testing.T) {
	t.Parallel()

	legacyHeader := "// Code generated by legacy. DO NOT EDIT."
	directory := &fakeOutputDirectory{
		files: map[string][]byte{
			"current.sql.go": []byte(testHeader + "\n\npackage db\n"),
			"legacy.sql.go":  []byte(legacyHeader + "\n\npackage db\n"),
			"other.sql.go":   []byte("// Code generated by other. DO NOT EDIT.\n\npackage db\n"),
		},
	}

	require.NoError(t, pruneStaleGeneratedFiles(directory, nil, "", testHeader, legacyHeader))

	assert.NotContains(t, directory.files, "current.sql.go")
	assert.NotContains(t, directory.files, "legacy.sql.go")
	assert.Contains(t, directory.files, "other.sql.go", "a header that is not listed must never mark a file as generated")
}

func TestPruneStaleGeneratedFilesRemovesOnlyStaleGeneratedFiles(t *testing.T) {
	t.Parallel()

	generated := []byte(testHeader + "\n\n" + "package db\n")
	directory := &fakeOutputDirectory{
		files: map[string][]byte{
			"stale.sql.go":   generated,
			"keep.sql.go":    generated,
			"models.go":      generated,
			"handwritten.go": []byte("package db\n"),
			"tiny.go":        []byte("//"),
			"subdir":         generated,
		},
		directories: map[string]bool{"subdir": true},
	}

	keep := map[string]struct{}{"keep.sql.go": {}, "models.go": {}}

	require.NoError(t, pruneStaleGeneratedFiles(directory, keep, testHeader))

	assert.NotContains(t, directory.files, "stale.sql.go", "a generated file absent from keep must be removed")
	assert.Contains(t, directory.files, "keep.sql.go", "a generated file still in keep must survive")
	assert.Contains(t, directory.files, "models.go", "a generated file still in keep must survive")
	assert.Contains(t, directory.files, "handwritten.go", "a file without the generated header must never be removed")
	assert.Contains(t, directory.files, "tiny.go", "a file shorter than the header must never be removed")
	assert.Contains(t, directory.files, "subdir", "a directory entry must never be removed")
}

func TestPruneStaleGeneratedFilesReturnsReadDirError(t *testing.T) {
	t.Parallel()

	sentinel := errors.New("cannot list directory")
	err := pruneStaleGeneratedFiles(&fakeOutputDirectory{readDirErr: sentinel}, nil, testHeader)

	require.ErrorIs(t, err, sentinel)
	assert.ErrorContains(t, err, "listing output directory")
}

func TestPruneStaleGeneratedFilesReturnsInspectError(t *testing.T) {
	t.Parallel()

	sentinel := errors.New("permission denied")
	directory := &fakeOutputDirectory{
		files:      map[string][]byte{"candidate.sql.go": []byte(testHeader + "\n\n")},
		openErrors: map[string]error{"candidate.sql.go": sentinel},
	}

	err := pruneStaleGeneratedFiles(directory, nil, testHeader)

	require.ErrorIs(t, err, sentinel)
	assert.ErrorContains(t, err, `inspecting candidate stale file "candidate.sql.go"`)
	assert.Contains(t, directory.files, "candidate.sql.go", "a file that cannot be inspected must not be removed")
}

