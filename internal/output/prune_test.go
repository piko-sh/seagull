func TestPruneStaleGeneratedFilesPassesOverEntriesThatAreNoRegularFile(t *testing.T) {
	t.Parallel()

	generated := []byte(testHeader + "\n\npackage db\n")
	tests := []struct {
		name string
		mode fs.FileMode
	}{
		{name: "a named pipe", mode: fs.ModeNamedPipe},
		{name: "a symbolic link", mode: fs.ModeSymlink},
		{name: "a socket", mode: fs.ModeSocket},
		{name: "a device", mode: fs.ModeDevice},
		{name: "a character device", mode: fs.ModeDevice | fs.ModeCharDevice},
		{name: "an irregular file", mode: fs.ModeIrregular},
	}
	for _, testCase := range tests {
		t.Run(testCase.name, func(t *testing.T) {
			t.Parallel()

			directory := &fakeOutputDirectory{
				files:      map[string][]byte{"special.sql.go": generated, "stale.sql.go": generated},
				modes:      map[string]fs.FileMode{"special.sql.go": testCase.mode},
				openErrors: map[string]error{"special.sql.go": errors.New("opening it would wait for a writer")},
			}

			scaling.Within(t, time.Second, func(context.Context) {
				require.NoError(t, pruneStaleGeneratedFiles(directory, nil, testHeader))
			})
			assert.Equal(t, []string{"stale.sql.go"}, directory.opened)
			assert.Contains(t, directory.files, "special.sql.go")
			assert.NotContains(t, directory.files, "stale.sql.go")
		})
	}
}

func TestPruneStaleGeneratedFilesRecognisesTheHeaderWhateverItsLineEnding(t *testing.T) {
	t.Parallel()

	tests := []struct {
		name        string
		content     string
		wantRemoved bool
	}{
		{name: "a line feed", content: testHeader + "\n\npackage db\n", wantRemoved: true},
		{name: "a carriage return and line feed", content: testHeader + "\r\n\r\npackage db\r\n", wantRemoved: true},
		{name: "the header alone with a carriage return and line feed", content: testHeader + "\r\n", wantRemoved: true},
		{name: "a carriage return alone", content: testHeader + "\rpackage db\n", wantRemoved: false},
		{name: "the header running on", content: testHeader + " (edited)\n", wantRemoved: false},
		{name: "the header with no line ending", content: testHeader, wantRemoved: false},
	}
	for _, testCase := range tests {
		t.Run(testCase.name, func(t *testing.T) {
			t.Parallel()

			directory := &fakeOutputDirectory{files: map[string][]byte{"stale.sql.go": []byte(testCase.content)}}

			require.NoError(t, pruneStaleGeneratedFiles(directory, nil, "// Code generated by other. DO NOT EDIT. And more.", testHeader))
			_, kept := directory.files["stale.sql.go"]
			assert.Equal(t, testCase.wantRemoved, !kept)
		})
	}
}
