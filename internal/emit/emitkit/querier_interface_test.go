const authorsQueryFile = `// Code generated by sgl. DO NOT EDIT.

package store

import (
	"context"
	"database/sql"

	uuid2 "github.com/google/uuid"
)

const getAuthorSQL = ` + "`SELECT id FROM authors WHERE id = $1`" + `

// GetAuthor reads one author.
//
// It fails with sql.ErrNoRows when none matches.
func (queries *Queries) GetAuthor(ctx context.Context, id uuid2.UUID) (GetAuthorRow, error) {
	return GetAuthorRow{}, nil
}

func (queries *Queries) DeleteAuthor(ctx context.Context, id uuid2.UUID) (sql.Result, error) {
	return nil, nil
}

func (queries *Queries) internal(ctx context.Context) error {
	return nil
}

func (builder *SearchAuthorsBuilder) All(ctx context.Context) ([]SearchAuthorsRow, error) {
	return nil, nil
}

func (queries *Queries) SearchAuthors(ctx context.Context) *SearchAuthorsBuilder {
	return &SearchAuthorsBuilder{}
}
`

const booksQueryFile = `package store

import "context"

func (queries *Queries) ListBooks(ctx context.Context, limit int) ([]ListBooksRow, error) {
	return nil, nil
}
`

const querierFile = `package store

import "database/sql"

func (queries *Queries) WithTx(transaction *sql.Tx) *Queries {
	return queries
}
`

const wantInterfaceFile = `package store

import (
	"context"
	"database/sql"

	uuid2 "github.com/google/uuid"
)

type Querier interface {
	DeleteAuthor(ctx context.Context, id uuid2.UUID) (sql.Result, error)
	// GetAuthor reads one author.
	//
	// It fails with sql.ErrNoRows when none matches.
	GetAuthor(ctx context.Context, id uuid2.UUID) (GetAuthorRow, error)
	ListBooks(ctx context.Context, limit int) ([]ListBooksRow, error)
	SearchAuthors(ctx context.Context) *SearchAuthorsBuilder
}

var _ Querier = (*Queries)(nil)
`

func interfaceNaming(name string) emit.Naming {
	return emit.Naming{
		Files:     map[string]string{"authors.sql": "authors.sql.go", "books.sql": "books.sql.go"},
		Imports:   map[string]string{"context": "context", "database/sql": "sql", "github.com/google/uuid": "uuid2"},
		Interface: name,
	}
}

func generatedFiles() []sqlmodel.GeneratedFile {
	return []sqlmodel.GeneratedFile{
		{Name: "authors.sql.go", Content: []byte(authorsQueryFile)},
		{Name: "books.sql.go", Content: []byte(booksQueryFile)},
		{Name: "querier.go", Content: []byte(querierFile)},
	}
}

func TestQuerierInterfaceListsTheQueryMethodsOfTheQueryFiles(t *testing.T) {
	t.Parallel()

	file, err := emitkit.QuerierInterface("store", interfaceNaming("Querier"), generatedFiles())

	require.NoError(t, err)
	require.Equal(t, "querier_interface.go", file.Name)
	require.Equal(t, wantInterfaceFile, string(file.Content))
}

func TestQuerierInterfaceTakesItsNameFromThePlan(t *testing.T) {
	t.Parallel()

	file, err := emitkit.QuerierInterface("store", interfaceNaming("Store"), generatedFiles())

	require.NoError(t, err)
	require.Contains(t, string(file.Content), "type Store interface {")
	require.Contains(t, string(file.Content), "var _ Store = (*Queries)(nil)")
}

func TestQuerierInterfaceIsNotWrittenWhenThePlanNamesNone(t *testing.T) {
	t.Parallel()

	file, err := emitkit.QuerierInterface("store", interfaceNaming(""), generatedFiles())

	require.NoError(t, err)
	require.Equal(t, sqlmodel.GeneratedFile{Name: "", Content: nil}, file)
}

func TestQuerierInterfaceOfAPackageWithoutQueriesHasNoMethods(t *testing.T) {
	t.Parallel()

	file, err := emitkit.QuerierInterface("store", emit.Naming{Interface: "Querier"}, nil)

	require.NoError(t, err)
	require.Contains(t, string(file.Content), "type Querier interface{}")
	require.Contains(t, string(file.Content), "var _ Querier = (*Queries)(nil)")
}

func TestQuerierInterfaceReportsAQueryFileThatDoesNotParse(t *testing.T) {
	t.Parallel()

	files := []sqlmodel.GeneratedFile{{Name: "authors.sql.go", Content: []byte("package store\n\nfunc (")}}

	_, err := emitkit.QuerierInterface("store", interfaceNaming("Querier"), files)

	require.ErrorContains(t, err, "authors.sql.go")
}
