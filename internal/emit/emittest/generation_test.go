const (
	recordedHeader = "// Code generated by seagull. DO NOT EDIT."
	notRecorded    = "the test records no generation of the case"
)

func recordedSubject(t *testing.T, engine dialect.DialectPort, generations map[string]*caseResult) *subject {
	t.Helper()

	for name := range generations {
		_, found := findCase(name)
		require.True(t, found, "the corpus has no case %s", name)
	}
	current := newSubject(&Suite{Name: "recorded", New: newSilentEmitter}, engine, &runtimeLane{})
	for name, state := range current.cases {
		result, recorded := generations[name]
		if !recorded {
			result = &caseResult{unusable: notRecorded}
		}
		state.generateOnce.Do(func() { state.result = result })
		state.checkOnce.Do(func() {
			if result.generated != nil && len(result.generated.Files) > 0 {
				result.checked = checkedWithoutToolchain(t, result.generated.Files...)
			}
		})
	}
	return current
}

func generatedFiles(files ...sqlmodel.GeneratedFile) *caseResult {
	generated := &app.Result{Header: recordedHeader, Files: files}
	return &caseResult{generated: generated, again: generated, reversed: generated}
}

func refusedGeneration(code, message string) *caseResult {
	refusal := diag.SourceError{Code: code, Severity: diag.SeverityError, Message: message}
	return &caseResult{generated: &app.Result{Header: recordedHeader, Diagnostics: []diag.SourceError{refusal}}}
}

func goFile(name, source string) sqlmodel.GeneratedFile {
	return sqlmodel.GeneratedFile{Name: name, Content: []byte(recordedHeader + "\n\n" + source)}
}

func replaced(t *testing.T, source, fragment, replacement string) string {
	t.Helper()

	require.Contains(t, source, fragment)
	return strings.Replace(source, fragment, replacement, 1)
}

func TestRecordedSubjectHoldsOnlyTheGenerationsGiven(t *testing.T) {
	t.Parallel()

	recorded := generatedFiles(goFile("answer.go", "package store\n\nvar Answer = 42\n"))
	current := recordedSubject(t, postgres.New(), map[string]*caseResult{caseCommands: recorded})

	require.Same(t, recorded, current.generation(t.Context(), caseCommands))
	require.NotNil(t, current.checkedOutput(t.Context(), caseCommands))
	require.Empty(t, current.checkedOutput(t.Context(), caseCommands).problems)
	require.Equal(t, notRecorded, current.generation(t.Context(), caseSlices).unusable)
	require.Nil(t, current.checkedOutput(t.Context(), caseSlices))
}

func TestGenerationRecordsAPanicAsTheCasesErrorAndLogsItOnce(t *testing.T) {
	t.Parallel()

	testCases := []struct {
		name     string
		emitter  func(*dialect.Facts) emit.EmitterPort
		expected string
		panics   bool
	}{
		{
			name:     "a panicking emitter constructor becomes the generation's error",
			emitter:  func(*dialect.Facts) emit.EmitterPort { panic("constructor boom") },
			expected: "generating the case: panic: constructor boom",
			panics:   true,
		},
		{
			name:     "a working emitter generates the case",
			emitter:  newSilentEmitter,
			expected: "",
			panics:   false,
		},
	}
	for _, testCase := range testCases {
		t.Run(testCase.name, func(t *testing.T) {
			t.Parallel()

			current := newSubject(&Suite{Name: "panics", New: testCase.emitter}, postgres.New(), &runtimeLane{})
			var output bytes.Buffer
			ctx := logging.ContextWithLogger(t.Context(), slog.New(slog.NewTextHandler(&output, nil)))

			first := current.generation(ctx, caseCommands)
			again := current.generation(ctx, caseCommands)

			require.Same(t, first, again, "a case is generated once")
			require.Empty(t, first.unusable)
			if !testCase.panics {
				require.NoError(t, first.generateError)
				require.Empty(t, output.String())
				return
			}
			require.ErrorIs(t, first.generateError, fault.ErrPanic)
			require.EqualError(t, first.generateError, testCase.expected)
			require.Nil(t, first.generated)
			require.Equal(t, 1, strings.Count(output.String(), "recovered a panic"))
			require.Contains(t, output.String(), "goroutine")
		})
	}
}

func TestFatalDiagnosticDescribesAFailureToAnalyseAtAll(t *testing.T) {
	t.Parallel()

	testCases := []struct {
		name     string
		err      error
		expected string
	}{
		{name: "a plain error", err: errors.New("the schema source failed"), expected: "the schema source failed"},
		{name: "a wrapped error", err: fmt.Errorf("creating the generator: %w", fault.ErrInvalidConfig), expected: "creating the generator: " + fault.ErrInvalidConfig.Error()},
	}
	for _, testCase := range testCases {
		t.Run(testCase.name, func(t *testing.T) {
			t.Parallel()

			diagnostic := fatalDiagnostic(testCase.err)

			require.Equal(t, diag.SeverityError, diagnostic.Severity)
			require.Equal(t, testCase.expected, diagnostic.Message)
			require.Empty(t, diagnostic.Filename)
			require.Zero(t, diagnostic.Line)
			require.Equal(t, []diag.SourceError{diagnostic}, errorDiagnostics([]diag.SourceError{diagnostic}))
		})
	}
}

func TestCorpusInputServesTheQueryFiles(t *testing.T) {
	t.Parallel()

	input := corpusInput(map[string]string{"items.sql": "SELECT 1;"})

	require.Nil(t, input.Migrations)
	require.Equal(t, generatedPackage, input.Package)
	content, err := fs.ReadFile(input.Queries, queryDirectory+"/items.sql")
	require.NoError(t, err)
	require.Equal(t, "SELECT 1;", string(content))
}

func TestErrorDiagnosticsKeepsOnlyErrors(t *testing.T) {
	t.Parallel()

	diagnostics := []diag.SourceError{
		{Code: "Q001", Severity: diag.SeverityError},
		{Code: "Q002", Severity: diag.SeverityWarning},
	}

	kept := errorDiagnostics(diagnostics)

	require.Len(t, kept, 1)
	require.Equal(t, "Q001", kept[0].Code)
	require.Len(t, diagnostics, 2)
	require.Equal(t, "[Q001 :0 ]", summarise(kept))
}

