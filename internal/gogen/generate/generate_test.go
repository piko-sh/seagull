func TestDropEmptyFilesKeepsTheFilesWithContentInOrder(t *testing.T) {
	t.Parallel()

	testCases := []struct {
		name  string
		files []sqlmodel.GeneratedFile
		want  []string
	}{
		{
			name:  "no files stay no files",
			files: nil,
			want:  []string{},
		},
		{
			name: "every empty file is dropped",
			files: []sqlmodel.GeneratedFile{
				{Name: "a.go", Content: nil},
				{Name: "b.go", Content: []byte{}},
			},
			want: []string{},
		},
		{
			name: "the files with content keep their order around the dropped ones",
			files: []sqlmodel.GeneratedFile{
				{Name: "a.go", Content: []byte("package a\n")},
				{Name: "b.go", Content: nil},
				{Name: "c.go", Content: []byte("package c\n")},
				{Name: "d.go", Content: []byte{}},
				{Name: "e.go", Content: []byte("package e\n")},
			},
			want: []string{"a.go", "c.go", "e.go"},
		},
	}
	for _, testCase := range testCases {
		t.Run(testCase.name, func(t *testing.T) {
			t.Parallel()

			kept := dropEmptyFiles(testCase.files)
			require.Equal(t, testCase.want, fileNames(kept))
			for _, dropped := range testCase.files[len(kept):] {
				require.Empty(t, dropped.Name, "a dropped file leaves no content behind in the backing array")
			}
		})
	}
}
