func TestPackageDeclaresOrderDirectionOnceForSortableQueriesInSeveralFiles(t *testing.T) {
	t.Parallel()

	first := dynamicSortableQuery(sqlmodel.QueryCommandMany)
	second := dynamicSortableQuery(sqlmodel.QueryCommandMany)
	second.Name = "SearchDrafts"
	second.Filename = "drafts.sql"
	emission := indexedEmission(true)
	emission.Request.Queries = []*sqlmodel.AnalysedQuery{first, second}

	files, err := Package(t.Context(), emission.Request, emission.Driver)
	require.NoError(t, err)

	fileSet := token.NewFileSet()
	parsed := make([]*ast.File, 0, len(files))
	declarations := 0
	for _, file := range files {
		if strings.Contains(string(file.Content), "type OrderDirection string") {
			declarations++
			require.Equal(t, "sortable.go", file.Name)
		}
		syntax, parseErr := parser.ParseFile(fileSet, file.Name, file.Content, parser.AllErrors)
		require.NoError(t, parseErr)
		parsed = append(parsed, syntax)
	}
	require.Equal(t, 1, declarations)
	config := types.Config{Importer: importer.Default()}
	_, err = config.Check(emission.Request.Package, fileSet, parsed, nil)
	require.NoError(t, err)
}

