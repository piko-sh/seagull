func TestCollectParenthesised(t *testing.T) {
	t.Parallel()

	testCases := []struct {
		name       string
		sql        string
		wantValues []string
		wantErr    bool
	}{
		{name: "nested group", sql: "(a, (b)) tail", wantValues: []string{"a", ",", "(", "b", ")"}},
		{name: "empty group", sql: "() tail", wantValues: nil},
		{name: "unmatched group", sql: "(a, (b) tail", wantErr: true},
		{name: "not a group", sql: "a", wantErr: true},
	}

	for _, testCase := range testCases {
		t.Run(testCase.name, func(t *testing.T) {
			t.Parallel()

			tokens, err := tokenise(testCase.sql)
			require.NoError(t, err)
			statementParser := newParser(tokens)

			inner, err := statementParser.collectParenthesised()

			if testCase.wantErr {
				require.Error(t, err)
				return
			}
			require.NoError(t, err)
			var values []string
			for _, innerToken := range inner {
				values = append(values, innerToken.Value)
			}
			assert.Equal(t, testCase.wantValues, values)
			assert.Equal(t, "tail", statementParser.Current().Value)
		})
	}
}

func TestCollectParenthesisedReturnsAReadOnlyView(t *testing.T) {
	t.Parallel()

	tokens, err := tokenise("(a) b")
	require.NoError(t, err)
	statementParser := newParser(tokens)

	inner, err := statementParser.collectParenthesised()
	require.NoError(t, err)
	extended := append(inner, token{Kind: tokenIdentifier, Value: "x", Start: 0})

	assert.Equal(t, "x", extended[1].Value)
	assert.Equal(t, ")", statementParser.Tokens[2].Value, "appending to the view must not overwrite the parser's tokens")
}

func TestNamedPlaceholdersAreNumberedAfterTheNumberedOnes(t *testing.T) {
	t.Parallel()

	testCases := []struct {
		name    string
		sql     string
		numbers map[string]int
	}{
		{
			name:    "a name written before an explicit $1",
			sql:     "UPDATE users SET name = :new_name WHERE id = $1 AND name = :old_name",
			numbers: map[string]int{"new_name": 2, "$1": 1, "old_name": 3},
		},
		{
			name:    "a name repeated around a higher number",
			sql:     "SELECT id FROM users WHERE name = :name AND id = $2 AND name <> :name",
			numbers: map[string]int{"name": 3, "$2": 2},
		},
		{
			name:    "a name inside a subquery before the numbered placeholder",
			sql:     "SELECT id FROM users WHERE id IN (SELECT user_id FROM posts WHERE title = :title) AND id = $1",
			numbers: map[string]int{"title": 2, "$1": 1},
		},
		{
			name:    "names alone count from one",
			sql:     "SELECT id FROM users WHERE id = :id AND name = :name",
			numbers: map[string]int{"id": 1, "name": 2},
		},
		{
			name:    "numbers alone keep their numbers",
			sql:     "SELECT id FROM users WHERE id = $2 AND name = $1",
			numbers: map[string]int{"$2": 2, "$1": 1},
		},
	}

	for _, testCase := range testCases {
		t.Run(testCase.name, func(t *testing.T) {
			t.Parallel()

			analysis := analyseQuery(t, nil, testCase.sql)
			numbers := map[string]int{}
			for _, reference := range analysis.ParameterReferences {
				key := reference.Name
				if key == "" {
					key = "$" + strconv.Itoa(reference.Number)
				}
				numbers[key] = reference.Number
			}
			require.Equal(t, testCase.numbers, numbers)
		})
	}
}

func TestADatabaseQualifierNamesTheSchemaQualifiedObject(t *testing.T) {
	t.Parallel()

	testCases := []struct {
		name       string
		sql        string
		wantKind   ast.MutationKind
		wantSchema string
		wantName   string
		wantColumn string
	}{
		{name: "create table", sql: "CREATE TABLE app.public.items (id int PRIMARY KEY, name text)",
			wantKind: ast.MutationCreateTable, wantSchema: "public", wantName: "items"},
		{name: "alter table", sql: "ALTER TABLE app.shop.items ADD COLUMN extra int",
			wantKind: ast.MutationAlterTableAddColumn, wantSchema: "shop", wantName: "items"},
		{name: "rename a column", sql: "ALTER TABLE app.public.items RENAME COLUMN extra TO other",
			wantKind: ast.MutationAlterTableRenameColumn, wantSchema: "public", wantName: "items", wantColumn: "extra"},
		{name: "move to a schema", sql: "ALTER TABLE app.public.items SET SCHEMA archive",
			wantKind: ast.MutationAlterTableSetSchema, wantSchema: "public", wantName: "items"},
		{name: "create view", sql: "CREATE VIEW app.public.items_view AS SELECT 1 AS id",
			wantKind: ast.MutationCreateView, wantSchema: "public", wantName: "items_view"},
		{name: "drop table", sql: "DROP TABLE app.public.items",
			wantKind: ast.MutationDropTable, wantSchema: "public", wantName: "items"},
		{name: "comment on a table", sql: "COMMENT ON TABLE app.public.items IS 'items'",
			wantKind: ast.MutationComment, wantSchema: "public", wantName: "items"},
		{name: "comment on a column of a database's table", sql: "COMMENT ON COLUMN app.public.items.name IS 'a name'",
			wantKind: ast.MutationComment, wantSchema: "public", wantName: "items", wantColumn: "name"},
		{name: "comment on a column of a schema's table", sql: "COMMENT ON COLUMN public.items.name IS 'a name'",
			wantKind: ast.MutationComment, wantSchema: "public", wantName: "items", wantColumn: "name"},
		{name: "comment on a column of a table", sql: "COMMENT ON COLUMN items.name IS 'a name'",
			wantKind: ast.MutationComment, wantSchema: "", wantName: "items", wantColumn: "name"},
	}

	for _, testCase := range testCases {
		t.Run(testCase.name, func(t *testing.T) {
			t.Parallel()

			engine := New()
			statements, err := engine.ParseStatements(t.Context(), testCase.sql)
			require.NoError(t, err)
			mutation, err := engine.ApplyDDL(t.Context(), statements[0])
			require.NoError(t, err)
			require.NotNil(t, mutation)
			require.Equal(t, testCase.wantKind, mutation.Kind)
			require.Equal(t, testCase.wantSchema, mutation.SchemaName)
			require.Equal(t, testCase.wantName, mutation.TableName)
			require.Equal(t, testCase.wantColumn, mutation.ColumnName)
		})
	}
}

func TestADatabaseQualifierNamesTheSchemaQualifiedSequenceTypeAndFunction(t *testing.T) {
	t.Parallel()

	engine := New()
	statements, err := engine.ParseStatements(t.Context(), "CREATE SEQUENCE app.public.counter;\n"+
		"CREATE TYPE app.public.mood AS ENUM ('calm');\n"+
		"CREATE FUNCTION app.public.answer() RETURNS int LANGUAGE sql AS 'SELECT 42';\n"+
		"CREATE INDEX items_name ON app.public.items (name);\n"+
		"CREATE TABLE app.public.orders (item_id int REFERENCES app.public.items (id));")
	require.NoError(t, err)
	mutations := make([]*ast.CatalogueMutation, 0, len(statements))
	for _, statement := range statements {
		mutation, applyError := engine.ApplyDDL(t.Context(), statement)
		require.NoError(t, applyError)
		mutations = append(mutations, mutation)
	}

	require.Equal(t, []string{"public", "counter"}, []string{mutations[0].SchemaName, mutations[0].SequenceName})
	require.Equal(t, []string{"public", "mood"}, []string{mutations[1].SchemaName, mutations[1].EnumName})
	require.Equal(t, []string{"public", "answer"}, []string{mutations[2].Function.Schema, mutations[2].Function.Name})
	require.Equal(t, []string{"public", "items"}, []string{mutations[3].SchemaName, mutations[3].TableName})
	require.Equal(t, []string{"public", "orders"}, []string{mutations[4].SchemaName, mutations[4].TableName})
}

