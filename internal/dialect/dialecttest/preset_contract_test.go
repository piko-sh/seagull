var seagullVocabulary = regexp.MustCompile(`(?i)sgl|seagull`)

var acmePreset = app.Preset{
	Directives: app.Directives{
		Canonical:        "acme",
		Aliases:          nil,
		Foreign:          nil,
		RequireCanonical: false,
	},
	Header:       "// Code generated by acme. DO NOT EDIT.",
	HelperPrefix: "acme",
	ErrorPrefix:  "acme",
	QueryNames:   emit.QueryNames{Enabled: true, File: "query_names.go", Function: "QueryName"},
	Types:        sqlmodel.TypeSlots{},
}

type presetRun struct {
	files       map[string][]byte
	err         error
	diagnostics []diag.SourceError
}

func rewrittenFiles(t *testing.T, caseDirectory string, replacer *strings.Replacer) fstest.MapFS {
	t.Helper()

	files := fstest.MapFS{}
	root := os.DirFS(caseDirectory)
	err := fs.WalkDir(root, ".", func(name string, entry fs.DirEntry, walkErr error) error {
		if walkErr != nil {
			return walkErr
		}
		if entry.IsDir() {
			files[name] = &fstest.MapFile{Mode: fs.ModeDir}
			return nil
		}
		content, err := fs.ReadFile(root, name)
		if err != nil {
			return err
		}
		files[name] = &fstest.MapFile{Data: []byte(replacer.Replace(string(content)))}
		return nil
	})
	require.NoError(t, err)
	return files
}

func prefixReplacer(prefix string) *strings.Replacer {
	return strings.NewReplacer("sgl.", prefix+".", "sgl(", prefix+"(")
}

func liveCaseDirectories(t *testing.T, engineName string) []string {
	t.Helper()

	root := filepath.Join("..", engineName, "testdata")
	entries, err := os.ReadDir(root)
	require.NoError(t, err)

	var directories []string
	for _, entry := range entries {
		directory := filepath.Join(root, entry.Name())
		if _, statErr := os.Stat(filepath.Join(directory, "migrations")); entry.IsDir() && statErr == nil {
			directories = append(directories, directory)
		}
	}
	require.NotEmpty(t, directories, "no %s golden case with migrations under %s", engineName, root)
	return directories
}

func runWithPreset(t *testing.T, engine compatEngine, emitter compatEmitter, caseDirectory string, servicePreset app.Preset, replacer *strings.Replacer) presetRun {
	t.Helper()

	specification := loadCompatSpec(t, caseDirectory)
	engineInstance := engine.newEngine()
	generator, err := app.New(engineInstance,
		app.WithEmitter(emitter.newEmitter(engineInstance)),
		app.WithPreset(servicePreset),
		app.WithCustomFunctions(specification.CustomFunctions...),
	)
	require.NoError(t, err)

	result, generateErr := generator.Generate(t.Context(), app.Input{
		Package:      "generated",
		Migrations:   rewrittenFiles(t, caseDirectory, replacer),
		MigrationDir: "migrations",
		QueryDir:     "queries",
	})
	run := presetRun{files: make(map[string][]byte), err: generateErr}
	if result != nil {
		run.diagnostics = result.Diagnostics
		for _, file := range result.Files {
			run.files[file.Name] = file.Content
		}
	}
	return run
}

func TestAcmePresetLeavesNoSeagullVocabulary(t *testing.T) {
	if testing.Short() {
		t.Skip("the preset contract generates every engine case; skipped under -short")
	}

	require.NoError(t, acmePreset.Validate())
	replacer := prefixReplacer("acme")
	generatedFiles := 0

	for _, engine := range compatEngines {
		for _, caseDirectory := range liveCaseDirectories(t, engine.name) {
			for _, emitter := range engine.emitters {
				key := engine.name + "/" + filepath.Base(caseDirectory) + "/" + emitter.name
				run := runWithPreset(t, engine, emitter, caseDirectory, acmePreset, replacer)
				if run.err != nil {
					assert.NotRegexpf(t, seagullVocabulary, run.err.Error(), "%s: error text", key)
				}
				for name, content := range run.files {
					generatedFiles++
					assert.NotRegexpf(t, seagullVocabulary, name, "%s: file name", key)
					assert.Falsef(t, seagullVocabulary.Match(content), "%s: %s names seagull:\n%s", key, name, firstVocabularyLine(content))
					assert.Truef(t, strings.HasPrefix(string(content), acmePreset.Header+"\n\n"), "%s: %s lacks the acme header", key, name)
				}
				for _, diagnostic := range run.diagnostics {
					assert.NotRegexpf(t, seagullVocabulary, diagnostic.Message, "%s: diagnostic %s", key, diagnostic.Code)
					assert.NotRegexpf(t, seagullVocabulary, diagnostic.Suggestion, "%s: diagnostic %s suggestion", key, diagnostic.Code)
				}
			}
		}
	}
	assert.Positive(t, generatedFiles)
}

func firstVocabularyLine(content []byte) string {
	for line := range strings.SplitSeq(string(content), "\n") {
		if seagullVocabulary.MatchString(line) {
			return line
		}
	}
	return ""
}

func TestAliasPrefixProducesIdenticalOutput(t *testing.T) {
	if testing.Short() {
		t.Skip("the alias contract generates every engine case; skipped under -short")
	}

	defaults := app.DefaultPreset()
	strict := app.DefaultPreset()
	strict.Directives.RequireCanonical = true
	identity := strings.NewReplacer()
	alias := prefixReplacer("seagull")
	compared := 0

	for _, engine := range compatEngines {
		for _, caseDirectory := range liveCaseDirectories(t, engine.name) {
			for _, emitter := range engine.emitters {
				key := engine.name + "/" + filepath.Base(caseDirectory) + "/" + emitter.name
				canonicalRun := runWithPreset(t, engine, emitter, caseDirectory, defaults, identity)
				aliasRun := runWithPreset(t, engine, emitter, caseDirectory, defaults, alias)

				assert.Equalf(t, canonicalRun.err != nil, aliasRun.err != nil, "%s: error presence", key)
				require.Equalf(t, len(canonicalRun.files), len(aliasRun.files), "%s: file set", key)
				for name, content := range canonicalRun.files {
					assert.Equalf(t, string(content), string(aliasRun.files[name]), "%s: %s differs under the alias", key, name)
				}
				assert.Equalf(t, diagnosticTexts(canonicalRun.diagnostics), diagnosticTexts(aliasRun.diagnostics), "%s: diagnostics", key)
				assert.NotContainsf(t, diagnosticCodes(aliasRun.diagnostics), diag.CodeAliasPrefix, "%s: Q050 without RequireCanonical", key)
				compared++

				if engine.name == "postgres" && filepath.Base(caseDirectory) == "001_basic_select" && emitter.name == "database_sql" {
					strictRun := runWithPreset(t, engine, emitter, caseDirectory, strict, alias)
					assert.Containsf(t, diagnosticCodes(strictRun.diagnostics), diag.CodeAliasPrefix, "%s: Q050 under RequireCanonical", key)
					strictCanonical := runWithPreset(t, engine, emitter, caseDirectory, strict, identity)
					assert.NotContainsf(t, diagnosticCodes(strictCanonical.diagnostics), diag.CodeAliasPrefix, "%s: Q050 for canonical", key)
				}
			}
		}
	}
	assert.Positive(t, compared)
}

func diagnosticTexts(diagnostics []diag.SourceError) []string {
	texts := make([]string, 0, len(diagnostics))
	for _, diagnostic := range diagnostics {
		texts = append(texts, fmt.Sprintf("%s %d %s %s %d", diagnostic.Filename, diagnostic.Line, diagnostic.Code, diagnostic.Message, diagnostic.Severity))
	}
	return texts
}

func diagnosticCodes(diagnostics []diag.SourceError) []string {
	codes := make([]string, 0, len(diagnostics))
	for _, diagnostic := range diagnostics {
		codes = append(codes, diagnostic.Code)
	}
	return codes
}

func TestForeignPrefixIsReportedNotParsed(t *testing.T) {
	t.Parallel()

	postgresIndex := slices.IndexFunc(compatEngines, func(engine compatEngine) bool { return engine.name == "postgres" })
	require.GreaterOrEqual(t, postgresIndex, 0)
	engine := compatEngines[postgresIndex]
	caseDirectory := filepath.Join("..", "postgres", "testdata", "001_basic_select")
	require.DirExists(t, caseDirectory)

	foreign := app.DefaultPreset().Directives.Foreign[0]
	run := runWithPreset(t, engine, databaseSQLEmitter, caseDirectory, app.DefaultPreset(), prefixReplacer(foreign))

	require.NoError(t, run.err)
	assert.Empty(t, run.files, "queries written only with a foreign prefix have no headers, so nothing is generated")
	var reported []diag.SourceError
	for _, diagnostic := range run.diagnostics {
		if diagnostic.Code == diag.CodeForeignPrefix {
			reported = append(reported, diagnostic)
		}
	}
	require.NotEmpty(t, reported)
	assert.Equal(t, diag.SeverityWarning, reported[0].Severity)
	assert.Equal(t,
		"-- "+foreign+".query is not enabled here; add "+foreign+" to directives.prefixes to accept it, then optionally format the directives to rewrite it to the canonical prefix",
		reported[0].Message)
	assert.Contains(t, diagnosticCodes(run.diagnostics), diag.CodeMissingDirective)
}
