const (
	// defaultHeader is the generated-file header of the default preset.
	defaultHeader = "// Code generated by sgl. DO NOT EDIT."

	// defaultQueryNamesFile is the default name of the optional query-names file.
	defaultQueryNamesFile = "query_names.go"

	// defaultQueryNamesFunction is the default name of the function in the query-names file.
	defaultQueryNamesFunction = "QueryName"

	// goFileSuffix is the extension every generated file name carries.
	goFileSuffix = ".go"

	// defaultSQLConstantSuffix ends the name of every SQL constant in the default preset,
	// keeping it clear of an import qualifier, such as getuserSQL rather than getuser.
	defaultSQLConstantSuffix = "SQL"

	// DefaultInterfaceName is the default name of the optional interface of the query
	// methods.
	DefaultInterfaceName = "Querier"

	// blankIdentifier is the blank identifier, which cannot name a declaration.
	blankIdentifier = "_"
)

var (
	// headerPattern is the shape Go tooling recognises as a generated-file marker.
	headerPattern = regexp.MustCompile(`^// Code generated .* DO NOT EDIT\.$`)

	// jsonCases lists the case styles json tags can be written in.
	jsonCases = []emit.JSONCase{emit.JSONCaseAsWritten, emit.JSONCaseSnake, emit.JSONCaseCamel, emit.JSONCasePascal}
)

// Settings is the form of a preset the generation stages consume. The app package's
// Preset, which the root package re-exports, converts to it.
type Settings struct {
	// Types holds the preset's type slots.
	Types sqlmodel.TypeSlots

	// Prefixes holds the directive prefixes recognised in SQL comments.
	Prefixes namespace.Set

	// Style controls the names, header and optional files of the generated code.
	Style emit.Style

	// RequireCanonical reports every directive written with an alias with a Q050 hint.
	RequireCanonical bool

	// NonNullElements declares the elements of arrays and lists, and the values of maps,
	// non-null where the engine can hold NULL among them, unless a column or a type override
	// declares otherwise.
	NonNullElements bool
}

// Validate reports whether the settings can be used.
//
// Every directive prefix must match [a-z][a-z0-9_]{0,31} and appear once across the
// canonical prefix, the aliases and the foreign prefixes. The header must have the
// generated-file shape, the helper and error prefixes the directive-prefix shape, an
// enabled query-names file a plain .go file name and an identifier function name, and an
// enabled interface an identifier name. The json tags' case must be one JSONCase names,
// and every struct tag one a generated tag can hold, with json left to the json tags.
//
// Returns error wrapping fault.ErrInvalidPrefix (itself wrapping fault.ErrInvalidConfig)
// for a bad prefix, or fault.ErrInvalidConfig for any other problem, when the settings
// cannot be used, or nil.
func (s *Settings) Validate() error {
	if err := validatePrefixes(s.Prefixes); err != nil {
		return err
	}
	if !headerPattern.MatchString(s.Style.Header) {
		return fmt.Errorf("%w: header %q must have the shape \"// Code generated <tool>. DO NOT EDIT.\"", fault.ErrInvalidConfig, s.Style.Header)
	}
	if !namespace.ValidPrefix(s.Style.HelperPrefix) {
		return fmt.Errorf("%w: helper prefix %q must match [a-z][a-z0-9_]{0,31}", fault.ErrInvalidPrefix, s.Style.HelperPrefix)
	}
	if !namespace.ValidPrefix(s.Style.ErrorPrefix) {
		return fmt.Errorf("%w: error prefix %q must match [a-z][a-z0-9_]{0,31}", fault.ErrInvalidPrefix, s.Style.ErrorPrefix)
	}
	if err := validateQueryNames(s.Style.QueryNames); err != nil {
		return err
	}
	return validateFieldStyle(&s.Style)
}

// DefaultSettings returns the settings of the default preset: the sgl directive prefix
// with its seagull alias, the sgl header, helper and error prefixes, the SQL suffix on
// SQL constant names, the built-in type defaults, and no query-names file.
//
// Returns Settings which is a fresh copy of the default settings.
func DefaultSettings() Settings {
	prefixes := namespace.Default()
	return Settings{
		Style: emit.Style{
			Header:       defaultHeader,
			HelperPrefix: prefixes.Canonical,
			ErrorPrefix:  prefixes.Canonical,
			JSONScanInto: sqlmodel.GoType{Composite: nil, Package: "", Name: ""},
			PackageNames: nil,
			QueryNames: emit.QueryNames{
				Enabled:  false,
				File:     defaultQueryNamesFile,
				Function: defaultQueryNamesFunction,
			},
			SQLConstantSuffix:    defaultSQLConstantSuffix,
			SQLConstantLowerCase: false,
			KeepStars:            false,
			StructTags:           nil,
			Interface:            emit.Interface{Enabled: false, Name: DefaultInterfaceName},
			JSONTags:             emit.JSONTags{Case: emit.JSONCaseAsWritten, Omit: false, OmitEmpty: false},
			EmptySlices:          false,
			DocComments:          false,
			ReuseModels:          false,
			ModernIdioms:         true,
			WrapErrors:           false,
		},
		Prefixes:         prefixes,
		Types:            sqlmodel.TypeSlots{},
		RequireCanonical: false,
		NonNullElements:  false,
	}
}

// IsDeclarableName reports whether a name can name a Go package or declaration: a Go
// identifier other than the blank identifier, which declares nothing.
//
// Takes name (string) which is the name.
//
// Returns bool which is true when the name is usable.
func IsDeclarableName(name string) bool {
	return token.IsIdentifier(name) && name != blankIdentifier
}

// validateFieldStyle checks the interface's name, the json tags' case and the struct tags
// of a style.
//
// Takes style (*emit.Style) which holds them.
//
// Returns error wrapping fault.ErrInvalidConfig for the first problem, or nil.
func validateFieldStyle(style *emit.Style) error {
	if style.Interface.Enabled && !IsDeclarableName(style.Interface.Name) {
		return fmt.Errorf("%w: interface name %q must be a Go identifier", fault.ErrInvalidConfig, style.Interface.Name)
	}
	if !slices.Contains(jsonCases, style.JSONTags.Case) {
		return fmt.Errorf("%w: json tag case %q must be snake, camel or pascal, or empty for the names as written", fault.ErrInvalidConfig, style.JSONTags.Case)
	}
	if _, found := style.StructTags[structtag.JSONKey]; found {
		return fmt.Errorf("%w: struct tags cannot give json, which the json tag settings shape", fault.ErrInvalidConfig)
	}
	if err := structtag.CheckAll(style.StructTags); err != nil {
		return fmt.Errorf("%w: %w", fault.ErrInvalidConfig, err)
	}
	return nil
}

// validatePrefixes checks every directive prefix's shape and that none repeats.
//
// Takes prefixes (namespace.Set) which holds the prefixes to check.
//
// Returns error wrapping fault.ErrInvalidPrefix for the first problem, or nil.
func validatePrefixes(prefixes namespace.Set) error {
	all := slices.Concat([]string{prefixes.Canonical}, prefixes.Aliases, prefixes.Foreign)
	seen := make(map[string]struct{}, len(all))
	for _, prefix := range all {
		if !namespace.ValidPrefix(prefix) {
			return fmt.Errorf("%w: directive prefix %q must match [a-z][a-z0-9_]{0,31}", fault.ErrInvalidPrefix, prefix)
		}
		if _, duplicate := seen[prefix]; duplicate {
			return fmt.Errorf("%w: directive prefix %q appears more than once", fault.ErrInvalidPrefix, prefix)
		}
		seen[prefix] = struct{}{}
	}
	return nil
}

// validateQueryNames checks an enabled query-names file has a usable file and function
// name.
//
// Takes names (emit.QueryNames) which holds the query-names settings.
//
// Returns error wrapping fault.ErrInvalidConfig for the first problem, or nil.
func validateQueryNames(names emit.QueryNames) error {
	if !names.Enabled {
		return nil
	}
	base := strings.TrimSuffix(names.File, goFileSuffix)
	if !strings.HasSuffix(names.File, goFileSuffix) || path.Base(names.File) != names.File || !token.IsIdentifier(strings.ReplaceAll(base, "-", "_")) {
		return fmt.Errorf("%w: query-names file %q must be a plain .go file name", fault.ErrInvalidConfig, names.File)
	}
	if strings.HasSuffix(base, "_test") || strings.HasPrefix(base, "_") {
		return fmt.Errorf("%w: query-names file %q would be ignored by the Go tool", fault.ErrInvalidConfig, names.File)
	}
	if !IsDeclarableName(names.Function) {
		return fmt.Errorf("%w: query-names function %q must be a Go identifier other than the blank identifier", fault.ErrInvalidConfig, names.Function)
	}
	return nil
}
