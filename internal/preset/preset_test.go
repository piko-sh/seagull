func TestDefaultSettingsValidate(t *testing.T) {
	t.Parallel()

	defaults := preset.DefaultSettings()

	require.NoError(t, defaults.Validate())
	assert.Equal(t, "sgl", defaults.Prefixes.Canonical)
	assert.Equal(t, "sgl", defaults.Style.HelperPrefix)
	assert.Equal(t, "sgl", defaults.Style.ErrorPrefix)
	assert.Equal(t, "// Code generated by sgl. DO NOT EDIT.", defaults.Style.Header)
	assert.Equal(t, "SQL", defaults.Style.SQLConstantSuffix)
	assert.False(t, defaults.Style.QueryNames.Enabled)
	assert.False(t, defaults.RequireCanonical)
}

func TestDefaultSettingsReturnIndependentCopies(t *testing.T) {
	t.Parallel()

	first := preset.DefaultSettings()
	first.Prefixes.Aliases[0] = "changed"

	assert.Equal(t, []string{"seagull"}, preset.DefaultSettings().Prefixes.Aliases)
}

func TestValidateWrapsSentinels(t *testing.T) {
	t.Parallel()

	badPrefix := preset.DefaultSettings()
	badPrefix.Prefixes.Foreign = append(badPrefix.Prefixes.Foreign, badPrefix.Prefixes.Foreign[0])
	require.ErrorIs(t, badPrefix.Validate(), fault.ErrInvalidPrefix)

	badHeader := preset.DefaultSettings()
	badHeader.Style.Header = ""
	err := badHeader.Validate()
	require.ErrorIs(t, err, fault.ErrInvalidConfig)
	assert.NotErrorIs(t, err, fault.ErrInvalidPrefix)

	badNames := preset.DefaultSettings()
	badNames.Style.QueryNames.Enabled = true
	badNames.Style.QueryNames.File = "names"
	require.ErrorIs(t, badNames.Validate(), fault.ErrInvalidConfig)
}

func TestValidateRejectsEachBadField(t *testing.T) {
	t.Parallel()

	testCases := map[string]func(*preset.Settings){
		"canonical shape": func(settings *preset.Settings) { settings.Prefixes.Canonical = "Bad" },
		"helper prefix":   func(settings *preset.Settings) { settings.Style.HelperPrefix = "" },
		"error prefix":    func(settings *preset.Settings) { settings.Style.ErrorPrefix = "a b" },
		"query-names test file": func(settings *preset.Settings) {
			settings.Style.QueryNames.Enabled = true
			settings.Style.QueryNames.File = "names_test.go"
		},
		"query-names hidden file": func(settings *preset.Settings) {
			settings.Style.QueryNames.Enabled = true
			settings.Style.QueryNames.File = "_names.go"
		},
		"query-names function": func(settings *preset.Settings) {
			settings.Style.QueryNames.Enabled = true
			settings.Style.QueryNames.Function = "1Name"
		},
		"blank query-names function": func(settings *preset.Settings) {
			settings.Style.QueryNames.Enabled = true
			settings.Style.QueryNames.Function = "_"
		},
		"interface name": func(settings *preset.Settings) {
			settings.Style.Interface.Enabled = true
			settings.Style.Interface.Name = "Querier interface"
		},
		"blank interface name": func(settings *preset.Settings) {
			settings.Style.Interface.Enabled = true
			settings.Style.Interface.Name = "_"
		},
		"json tag case": func(settings *preset.Settings) { settings.Style.JSONTags.Case = "kebab" },
		"struct tag naming json": func(settings *preset.Settings) {
			settings.Style.StructTags = map[string]string{"json": "{name}"}
		},
		"struct tag key": func(settings *preset.Settings) {
			settings.Style.StructTags = map[string]string{"my key": "{name}"}
		},
		"struct tag value": func(settings *preset.Settings) {
			settings.Style.StructTags = map[string]string{"db": "a`b"}
		},
	}

	for name, mutate := range testCases {
		t.Run(name, func(t *testing.T) {
			t.Parallel()

			candidate := preset.DefaultSettings()
			mutate(&candidate)

			assert.ErrorIs(t, candidate.Validate(), fault.ErrInvalidConfig)
		})
	}
}

func TestDefaultSettingsLeaveTheGeneratedCodeOptionsOff(t *testing.T) {
	t.Parallel()

	defaults := preset.DefaultSettings()

	require.False(t, defaults.Style.Interface.Enabled)
	require.Equal(t, preset.DefaultInterfaceName, defaults.Style.Interface.Name)
	require.Equal(t, emit.JSONTags{Case: emit.JSONCaseAsWritten, Omit: false, OmitEmpty: false}, defaults.Style.JSONTags)
	require.Nil(t, defaults.Style.StructTags)
	require.False(t, defaults.Style.EmptySlices)
	require.False(t, defaults.Style.DocComments)
}

func TestValidateAcceptsTheGeneratedCodeOptions(t *testing.T) {
	t.Parallel()

	candidate := preset.DefaultSettings()
	candidate.Style.Interface = emit.Interface{Enabled: true, Name: "store"}
	candidate.Style.JSONTags = emit.JSONTags{Case: emit.JSONCaseCamel, Omit: false, OmitEmpty: true}
	candidate.Style.StructTags = map[string]string{"db": "{name}", "validate": "required"}
	candidate.Style.EmptySlices = true
	candidate.Style.DocComments = true

	require.NoError(t, candidate.Validate())
}

func TestIsDeclarableNameRefusesTheBlankIdentifier(t *testing.T) {
	t.Parallel()

	testCases := []struct {
		name string
		want bool
	}{
		{name: "store", want: true},
		{name: "_store", want: true},
		{name: "Querier", want: true},
		{name: "_", want: false},
		{name: "", want: false},
		{name: "not-a-name", want: false},
		{name: "1name", want: false},
		{name: "func", want: false},
	}
	for _, testCase := range testCases {
		t.Run(testCase.name, func(t *testing.T) {
			t.Parallel()

			assert.Equal(t, testCase.want, preset.IsDeclarableName(testCase.name))
		})
	}
}
