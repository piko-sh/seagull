# hack/generate/diagnostics.sh - Generate the diagnostic reference from the code table
#
# The reference is rendered by `sgl explain --format markdown`, which reads the same table
# (seagull.Codes) that `sgl explain Q012` prints from, so the page and the command never
# disagree.
#
# Usage:
#   ./hack/generate/diagnostics.sh              Rewrite docs/reference/diagnostics.md
#   ./hack/generate/diagnostics.sh --validate   Fail when docs/reference/diagnostics.md is stale

# shellcheck source=../lib/init.sh
source "$(dirname "$0")/../lib/init.sh"

# The generated page.
readonly OUTPUT_FILE="${SEAGULL_ROOT}/docs/reference/diagnostics.md"

# generate_reference renders the reference page into a file.
# Arguments:
#   $1 - File to write
generate_reference() {
    {
        cat <<'HEADER'
---
title: "Diagnostics"
description: "Every diagnostic code sgl reports: what it means, how severe it is and how to fix it."
section: "Reference"
order: 40
---

<!-- Generated by hack/generate/diagnostics.sh from the diagnostic code table. Do not edit. -->

# Diagnostics

`sgl generate` and `sgl vet` report problems as diagnostics, each with a stable code.
An error in a query leaves that query out of `sgl generate`, which writes the rest of
the package and exits with status 1; any other error, such as one in a migration, stops
code generation. Warnings and hints do neither, and are findings only under
`sgl vet --strict`. `sgl explain Q012` prints any entry below in the terminal.

HEADER
        "${GO}" run ./cmd/sgl explain --format markdown
    } > "$1"
}

# validate_reference fails when the committed page no longer matches the code table.
# Globals:
#   OUTPUT_FILE - Read
# Arguments:
#   $1 - File holding the freshly rendered page
validate_reference() {
    if ! diff -u "$OUTPUT_FILE" "$1" >&2; then
        seagull::log::error "docs/reference/diagnostics.md is stale"
        seagull::log::info "Regenerate with: make generate-diagnostics"
        exit 1
    fi
}

# main generates or validates the diagnostic reference.
# Arguments:
#   $1 - --validate to check the committed file instead of rewriting it
main() {
    local rendered
    rendered=$(mktemp)
    # shellcheck disable=SC2064
    trap "rm -f '${rendered}'" EXIT

    if [[ "${1:-}" == "--validate" ]]; then
        seagull::log::header "Validating the diagnostic reference"
        generate_reference "$rendered"
        validate_reference "$rendered"
        seagull::log::footer
        seagull::log::success "diagnostic reference is up to date"
        return 0
    fi

    seagull::log::header "Generating the diagnostic reference"

    generate_reference "$rendered"
    cp "$rendered" "$OUTPUT_FILE"

    seagull::log::footer
    seagull::log::success "diagnostic reference generation complete!"
}

main "$@"
