# hack/generate/examples.sh - Regenerate, or check, the generated code of every example
#
# Each variant, examples/<module>/<NNN>_<slug>, commits the code this checkout's sgl
# writes. --validate also runs the curriculum, equivalent-cell and expected-diagnostics
# checks in examples/catalogue.
#
# Usage:
#   ./hack/generate/examples.sh              Regenerate every variant
#   ./hack/generate/examples.sh --validate   Fail when a variant is stale or a check fails

# shellcheck source=../lib/init.sh
source "$(dirname "$0")/../lib/init.sh"

# The directory holding the examples.
readonly EXAMPLES_DIR="${SEAGULL_ROOT}/examples"

# The curriculum's own module: the loader, the validator and the twin check.
readonly CATALOGUE_DIR="${EXAMPLES_DIR}/catalogue"

# Array of variants, and checks, that failed or were stale.
FAILED=()

# Set to 1 by --validate.
VALIDATE=0

# run_in runs a command in a variant directory, printing its output only when it fails.
# Arguments:
#   $1 - Variant directory
#   $@ - Command to run
# Returns:
#   The command's exit status
run_in() {
    local dir="$1"
    shift
    local output status=0
    output="$( cd "$dir" && "$@" 2>&1 )" || status=$?
    if [[ "$status" -ne 0 ]]; then
        printf '%s\n' "$output" >&2
    fi
    return "$status"
}

# generate_variant generates, or checks, one variant's committed code.
# Globals:
#   VALIDATE - Read
# Arguments:
#   $1 - Variant directory
#   $2 - Variant directory, relative to EXAMPLES_DIR
#   $3 - Path to the sgl binary
# Returns:
#   0 when the variant is current (or was regenerated), 1 otherwise
generate_variant() {
    local dir="$1" relative="$2" sgl="$3"
    local check=()
    if [[ "$VALIDATE" -eq 1 ]]; then
        check=(--check)
    fi

    case "$relative" in
        embedding/046_library_generate)
            # Generated by the library; the stock sgl must agree with it.
            if [[ "$VALIDATE" -eq 1 ]]; then
                run_in "$dir" "${GO}" run . -check || return 1
            else
                run_in "$dir" "${GO}" run . || return 1
            fi
            run_in "$dir" "$sgl" generate --check || return 1
            ;;

        embedding/052_custom_emitter)
            # Written by the program's own emitter, which the stock sgl would prune.
            if [[ "$VALIDATE" -eq 1 ]]; then
                run_in "$dir" "${GO}" test -count=1 -run '^TestCommittedStoreIsCurrent$' . || return 1
            else
                run_in "$dir" "${GO}" run . -write || return 1
            fi
            ;;

        embedding/053_custom_sgl_binary)
            # A custom sgl, which generates its own code.
            run_in "$dir" "${GO}" run . generate "${check[@]+"${check[@]}"}" || return 1
            ;;

        embedding/047_library_vet_and_catalogue | embedding/049_presets | \
            embedding/050_schema_from_live_database | embedding/051_generator_observability | \
            tooling/041_vet_and_diagnostics | tooling/043_describe_and_schema | \
            tooling/044_fmt_and_prefixes | tooling/045_migrate_from_the_cli)
            # These commit no generated code; their tests cover them.
            return 0
            ;;

        *)
            run_in "$dir" "$sgl" generate "${check[@]+"${check[@]}"}" || return 1
            ;;
    esac

    run_in "$dir" "$sgl" fmt --check || return 1
}

# generate_module generates, or checks, every variant in one examples module, and fails
# a module with no variant directories.
# Globals:
#   EXAMPLES_DIR - Read
#   FAILED - Modified with failed variants, or the module when it has none
# Arguments:
#   $1 - Module directory
#   $2 - Path to the sgl binary
generate_module() {
    local module="$1" sgl="$2"
    local name found=0 count=0 failed=0 dir relative
    name="$(basename "$module")"

    for dir in "${module}"/[0-9][0-9][0-9]_*/; do
        [[ -d "$dir" ]] || continue
        found=$((found + 1))
        dir="${dir%/}"
        relative="${dir#"${EXAMPLES_DIR}"/}"
        [[ -f "${dir}/sgl.yaml" ]] || continue
        count=$((count + 1))
        if ! generate_variant "$dir" "$relative" "$sgl"; then
            seagull::log::error "$relative"
            FAILED+=("$relative")
            failed=$((failed + 1))
        fi
    done

    if [[ "$found" -eq 0 ]]; then
        seagull::log::error "${name}: no variant directories (NNN_slug) found"
        FAILED+=("${name}")
        return 0
    fi
    if [[ "$count" -eq 0 ]]; then
        return 0
    fi
    if [[ "$failed" -eq 0 ]]; then
        seagull::log::success "${name}: ${count} variants"
    else
        seagull::log::error "${name}: ${failed} of ${count} variants stale or failing"
    fi
}

# validate_curriculum runs the catalogue's tests, TestCurriculumIsValid among them.
# Globals:
#   CATALOGUE_DIR - Read
#   FAILED - Modified when the curriculum is invalid
validate_curriculum() {
    seagull::log::info "curriculum (examples/catalogue)"
    if ( cd "$CATALOGUE_DIR" && "${GO}" test -count=1 ./... ); then
        seagull::log::success "curriculum"
    else
        seagull::log::error "curriculum"
        FAILED+=("curriculum")
    fi
}

# check_twins proves every equivalent cell in concepts.yaml generates its twin's code.
# Globals:
#   CATALOGUE_DIR - Read
#   FAILED - Modified when a cell differs
# Arguments:
#   $1 - Path to the sgl binary
check_twins() {
    local sgl="$1"
    seagull::log::info "equivalent cells (examples/catalogue/cmd/twins)"
    if ( cd "$CATALOGUE_DIR" && "${GO}" run ./cmd/twins -examples .. -sgl "$sgl" ); then
        seagull::log::success "equivalent cells"
    else
        seagull::log::error "equivalent cells; add -diff to the twins command to see what differs"
        FAILED+=("twins")
    fi
}

# check_diagnostics proves sgl vet reports exactly each variant's expected_diagnostics.
# Globals:
#   CATALOGUE_DIR - Read
#   FAILED - Modified when a variant differs
# Arguments:
#   $1 - Path to the sgl binary
check_diagnostics() {
    local sgl="$1"
    seagull::log::info "expected diagnostics (examples/catalogue/cmd/vetcheck)"
    if ( cd "$CATALOGUE_DIR" && "${GO}" run ./cmd/vetcheck -examples .. -sgl "$sgl" -go "${GO}" ); then
        seagull::log::success "expected diagnostics"
    else
        seagull::log::error "expected diagnostics; add -v to the vetcheck command to see every variant"
        FAILED+=("diagnostics")
    fi
}

# main builds sgl once and generates, or checks, every variant of every examples module
# other than the catalogue's own.
# Globals:
#   CATALOGUE_DIR - Read
#   FAILED - Read
#   SEAGULL_ROOT - Read
#   VALIDATE - Set by --validate
# Arguments:
#   $1 - --validate to check the committed files instead of rewriting them
main() {
    if [[ "${1:-}" == "--validate" ]]; then
        VALIDATE=1
        seagull::log::header "Validating the example projects"
    else
        seagull::log::header "Generating the example projects"
    fi

    local workdir
    workdir=$(mktemp -d)
    # shellcheck disable=SC2064
    trap "rm -rf '${workdir}'" EXIT

    local sgl="${workdir}/sgl"
    "${GO}" build -o "$sgl" ./cmd/sgl

    local module
    while IFS= read -r module; do
        module="${SEAGULL_ROOT}/${module}"
        [[ "$module" != "$CATALOGUE_DIR" ]] || continue
        generate_module "$module" "$sgl"
    done < <(seagull::go::example_dirs)

    if [[ "$VALIDATE" -eq 1 ]]; then
        validate_curriculum
        check_twins "$sgl"
        check_diagnostics "$sgl"
    fi

    if [[ ${#FAILED[@]} -gt 0 ]]; then
        seagull::log::fatal "stale or failing: ${FAILED[*]}; run make generate-examples, or see the messages above"
    fi

    seagull::log::footer

    if [[ "$VALIDATE" -eq 1 ]]; then
        seagull::log::success "example projects are up to date"
    else
        seagull::log::success "example project generation complete!"
    fi
}

main "$@"
