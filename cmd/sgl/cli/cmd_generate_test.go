func TestGenerateAddsNewFilesInDiff(t *testing.T) {
	t.Parallel()

	project := sqliteProject(t)
	result := project.Run("generate", "--diff")
	requireCode(t, result, 0)
	assert.Contains(t, result.Stdout, "--- /dev/null")
	assert.False(t, project.Exists("internal/store"))
	requireCode(t, project.Run("generate"), 0)
	models := project.Read("internal/store/models.go")
	lines := strings.Count(models, "\n")

	header, body, found := strings.Cut(result.Stdout, "+++ b/internal/store/models.go\n")
	require.True(t, found)
	require.True(t, strings.HasSuffix(header, "--- /dev/null\n"))
	hunk, rest, _ := strings.Cut(body, "\n")
	require.Equal(t, fmt.Sprintf("@@ -0,0 +1,%d @@", lines), hunk)
	added := strings.SplitAfterN(rest, "\n", lines+1)
	require.Equal(t, "+"+strings.ReplaceAll(strings.TrimSuffix(models, "\n"), "\n", "\n+")+"\n", strings.Join(added[:lines], ""))
}

