func TestGenerateCheckDiffAndDryRunWriteNothing(t *testing.T) {
	t.Parallel()

	project := sqliteProject(t)
	requireCode(t, project.Run("generate"), 0)
	before := project.Read("internal/store/example.sql.go")
	project.Write("db/queries/example.sql", strings.Replace(project.Read("db/queries/example.sql"), "ORDER BY name", "ORDER BY bio", 1))
	project.Write("internal/store/stale.go", "// Code generated by sgl. DO NOT EDIT.\npackage store\n")
	project.Write("internal/store/handwritten.go", "package store\n")

	result := project.Run("generate", "--check")
	requireCode(t, result, 1)
	assert.Contains(t, result.Stderr, "out of date")
	assert.Contains(t, result.Stderr, "modify internal/store/example.sql.go")
	assert.Contains(t, result.Stderr, "remove internal/store/stale.go")

	result = project.Run("generate", "--diff")
	requireCode(t, result, 0)
	assert.Contains(t, result.Stdout, "--- a/internal/store/example.sql.go")
	assert.Contains(t, result.Stdout, "+const listAuthorsSQL = `SELECT id, name, bio FROM authors ORDER BY bio;`")
	assert.Contains(t, result.Stdout, "+++ /dev/null")

	result = project.Run("generate", "--dry-run")
	requireCode(t, result, 0)
	assert.Contains(t, result.Stdout, "modify internal/store/example.sql.go")
	assert.Equal(t, before, project.Read("internal/store/example.sql.go"))

	result = project.Run("generate", "--check", "--diff")
	requireCode(t, result, 1)
	assert.Contains(t, result.Stdout, "+++ b/internal/store/example.sql.go")

	requireCode(t, project.Run("generate"), 0)
	assert.False(t, project.Exists("internal/store/stale.go"))
	assert.True(t, project.Exists("internal/store/handwritten.go"))
	assert.Contains(t, project.Read("internal/store/example.sql.go"), "ORDER BY bio")
}

func TestGenerateLeavesUnchangedFilesAlone(t *testing.T) {
	t.Parallel()

	project := sqliteProject(t)
	requireCode(t, project.Run("generate"), 0)
	past := time.Date(2001, time.February, 3, 4, 5, 6, 0, time.UTC)
	names := []string{"models.go", "querier.go", "example.sql.go"}
	for _, name := range names {
		require.NoError(t, os.Chtimes(project.Path("internal/store/"+name), past, past))
	}
	project.Write("db/queries/example.sql", strings.Replace(project.Read("db/queries/example.sql"), "ORDER BY name", "ORDER BY bio", 1))

	result := project.Run("generate")

	requireCode(t, result, 0)
	require.Contains(t, result.Stdout, "(1 changed)")
	for _, name := range names {
		info, err := os.Stat(project.Path("internal/store/" + name))
		require.NoError(t, err)
		require.Equal(t, name == "example.sql.go", !info.ModTime().Equal(past), name)
	}
}

func TestGenerateWithoutAQueryDirectory(t *testing.T) {
	t.Parallel()

	testCases := []struct {
		name    string
		queries string
		stderr  string
		code    int
	}{
		{name: "left out of the configuration, generates the models alone", queries: "", code: 0},
		{name: "named in the configuration, is an error naming it", queries: "    queries: db/querys\n", code: 2,
			stderr: `database "app": the query directory db/querys does not exist; create it, or correct queries in sgl.yaml`},
	}
	for _, testCase := range testCases {
		t.Run(testCase.name, func(t *testing.T) {
			t.Parallel()
			project := sqliteProject(t)
			require.NoError(t, os.RemoveAll(project.Path("db/queries")))
			project.Write("sgl.yaml", "version: 1\ndatabases:\n  - name: app\n    dialect: sqlite\n    migrations: db/migrations\n"+
				testCase.queries+"    go:\n      package: store\n      out: internal/store\n")

			result := project.Run("generate")

			requireCode(t, result, testCase.code)
			require.Contains(t, result.Stderr, testCase.stderr)
			require.Equal(t, testCase.code == 0, project.Exists("internal/store/models.go"))
		})
	}
}

func TestCommandsThatReplayTheMigrationsNeedTheirDirectory(t *testing.T) {
	t.Parallel()

	defaultMissing := `database "app": the migration directory db/migrations does not exist; create it, or set migrations in sgl.yaml ` +
		`to the directory that holds them`
	namedMissing := `database "app": the migration directory db/schema does not exist; create it, or correct migrations in sgl.yaml`
	testCases := []struct {
		name       string
		migrations string
		stderr     string
		command    []string
	}{
		{name: "generate, the default directory", command: []string{"generate"}, stderr: defaultMissing},
		{name: "generate, a named directory", migrations: "    migrations: db/schema\n", command: []string{"generate"}, stderr: namedMissing},
		{name: "vet, the default directory", command: []string{"vet"}, stderr: defaultMissing},
		{name: "schema dump, a named directory", migrations: "    migrations: db/schema\n", command: []string{"schema", "dump"}, stderr: namedMissing},
	}
	for _, testCase := range testCases {
		t.Run(testCase.name, func(t *testing.T) {
			t.Parallel()
			project := sqliteProject(t)
			require.NoError(t, os.RemoveAll(project.Path("db/migrations")))
			project.Write("sgl.yaml", "version: 1\ndatabases:\n  - name: app\n    dialect: sqlite\n"+testCase.migrations+
				"    go:\n      package: store\n      out: internal/store\n")

			result := project.Run(testCase.command...)

			requireCode(t, result, 2)
			require.Contains(t, result.Stderr, testCase.stderr)
			require.NotContains(t, result.Stderr, "open .")
			require.False(t, project.Exists("internal/store/models.go"))
		})
	}
}

