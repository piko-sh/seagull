func TestGenerateRejectsUnusableConfiguration(t *testing.T) {
	t.Parallel()

	tests := []struct {
		name   string
		config string
		stderr string
	}{
		{name: "pgx on sqlite", config: "driver: pgx", stderr: "pgx needs a dialect that runs on pgx, such as postgres"},
		{name: "clickhouse on sqlite", config: "driver: clickhouse", stderr: "clickhouse needs a dialect that runs on clickhouse-go, such as clickhouse"},
		{name: "unknown driver", config: "driver: odbc", stderr: `unknown go.driver "odbc"`},
		{name: "prepared pgx", config: "driver: pgx\n      prepared: true", stderr: "go.prepared applies only"},
		{name: "pointer slot", config: "types: { decimal: \"*string\" }", stderr: "nullable columns become pointers"},
		{name: "slashed builtin", config: "types: { decimal: \"a/b\" }", stderr: "must be import/path.Name"},
		{name: "unexported type", config: "types: { decimal: \"example.com/x.lower\" }", stderr: "exported Name"},
		{name: "bad override", config: "types: { overrides: [ { sql: text, go: \"*x\" } ] }", stderr: "overrides[0]"},
	}
	for _, testCase := range tests {
		t.Run(testCase.name, func(t *testing.T) {
			t.Parallel()

			project := sqliteProject(t)
			project.Write("sgl.yaml", "databases:\n  - name: app\n    dialect: sqlite\n    go:\n      "+testCase.config+"\n")
			result := project.Run("generate")
			requireCode(t, result, 2)
			assert.Contains(t, result.Stderr, testCase.stderr)
		})
	}

	project := sqliteProject(t)
	project.Write("sgl.yaml", "databases:\n  - name: app\n    dialect: nosuch\n")
	result := project.Run("generate")
	requireCode(t, result, 2)
	assert.Contains(t, result.Stderr, "unknown dialect")

	project.Write("sgl.yaml", "databases:\n  - name: app\n    dialect: sqlite\n    queries: missing\n")
	requireCode(t, project.Run("generate"), 2)

	requireCode(t, sqliteProject(t).Run("generate", "extra"), 2)
}

