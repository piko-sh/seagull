const generatedHeader = "// Code generated by sgl. DO NOT EDIT."

func TestPlanChangesReadsOnlyWhatItNeeds(t *testing.T) {
	t.Parallel()

	tests := []struct {
		name        string
		existing    map[string]string
		keepContent bool
		want        []fileChange
	}{
		{
			name:     "an unchanged file",
			existing: map[string]string{"models.go": generatedHeader + "\npackage store\n"},
			want:     nil,
		},
		{
			name:     "a longer file is changed without being read whole",
			existing: map[string]string{"models.go": generatedHeader + "\npackage store\n" + strings.Repeat("// more\n", 1000)},
			want:     []fileChange{{kind: changeModified, before: nil}},
		},
		{
			name:        "a longer file is read whole for a diff",
			existing:    map[string]string{"models.go": generatedHeader + "\npackage store\n// more\n"},
			keepContent: true,
			want:        []fileChange{{kind: changeModified, before: []byte(generatedHeader + "\npackage store\n// more\n")}},
		},
		{
			name: "a stale generated file and a file of the user's own",
			existing: map[string]string{
				"models.go": generatedHeader + "\npackage store\n",
				"old.go":    generatedHeader + "\npackage store\n" + strings.Repeat("// stale\n", 1000),
				"mine.go":   "package store\n",
			},
			want: []fileChange{{kind: changeRemoved, before: nil}},
		},
		{
			name: "a stale generated file whose lines end with a carriage return",
			existing: map[string]string{
				"models.go":  generatedHeader + "\npackage store\n",
				"windows.go": generatedHeader + "\r\npackage store\r\n",
			},
			want: []fileChange{{kind: changeRemoved, before: nil}},
		},
		{
			name: "a file whose first line only starts with the header",
			existing: map[string]string{
				"models.go":  generatedHeader + "\npackage store\n",
				"longer.go":  generatedHeader + " Edited.\npackage store\n",
				"partial.go": generatedHeader + "\r",
			},
			want: nil,
		},
	}

	for _, testCase := range tests {
		t.Run(testCase.name, func(t *testing.T) {
			t.Parallel()

			directory := t.TempDir()
			for name, content := range testCase.existing {
				require.NoError(t, os.WriteFile(filepath.Join(directory, name), []byte(content), 0o600))
			}
			files := []emit.GeneratedFile{{Name: "models.go", Content: []byte(generatedHeader + "\npackage store\n")}}

			changes, err := planChanges(directory, files, []string{generatedHeader}, testCase.keepContent)

			require.NoError(t, err)
			require.Len(t, changes, len(testCase.want))
			for index, want := range testCase.want {
				assert.Equal(t, want.kind, changes[index].kind)
				assert.Equal(t, want.before, changes[index].before)
			}
		})
	}
}

func TestPlanChangesInADirectoryThatDoesNotExist(t *testing.T) {
	t.Parallel()

	directory := filepath.Join(t.TempDir(), "missing")
	files := []emit.GeneratedFile{{Name: "b.go", Content: []byte("b")}, {Name: "empty.go", Content: nil}, {Name: "a.go", Content: []byte("a")}}

	changes, err := planChanges(directory, files, []string{generatedHeader}, false)

	require.NoError(t, err)
	require.Len(t, changes, 2)
	assert.Equal(t, filepath.Join(directory, "a.go"), changes[0].path)
	assert.Equal(t, changeAdded, changes[1].kind)
}

func TestStaleFilesSkipsWhatIsNotARegularFile(t *testing.T) {
	t.Parallel()

	directory := t.TempDir()
	require.NoError(t, os.Mkdir(filepath.Join(directory, "nested"), 0o750))
	require.NoError(t, os.WriteFile(filepath.Join(directory, "target.go"), []byte(generatedHeader+"\n"), 0o600))
	if err := os.Symlink(filepath.Join(directory, "target.go"), filepath.Join(directory, "link.go")); err != nil {
		t.Skipf("symbolic links are unavailable: %v", err)
	}

	changes, err := planChanges(directory, nil, []string{generatedHeader}, false)

	require.NoError(t, err)
	require.Len(t, changes, 1, "only the regular file is stale")
	assert.Equal(t, filepath.Join(directory, "target.go"), changes[0].path)
}
