	for _, diagnostic := range report.Diagnostics {
		if diagnostic.Code == seagull.CodeForeignPrefix {
			found = true
		}
	}
	assert.True(t, found, "a directive with a foreign prefix is reported, got %+v", report.Diagnostics)
