package facade_test

import (
	"testing"

	"github.com/stretchr/testify/require"

	"seagull.sh/seagull"
)

const interfaceQueries = `-- Lists every post.
-- sgl.query(ListPosts, many)
SELECT id, title FROM posts;

-- sgl.query(SearchPosts, many, dynamic: runtime)
SELECT id, title FROM posts;

-- sgl.query(DeletePost, exec)
DELETE FROM posts WHERE id = $1;
`

const interfaceClickHouseQueries = `-- Lists every post.
-- sgl.query(ListPosts, many)
SELECT id, title FROM posts;

-- sgl.query(SearchPosts, many, dynamic: runtime)
SELECT id, title FROM posts;

-- sgl.query(DeletePost, exec)
INSERT INTO posts (id, title) VALUES ({id:UInt64}, {title:String});
`

func interfaceQueriesFor(target featureTarget) string {
	if target.migration == featureClickHouseMigration {
		return interfaceClickHouseQueries
	}
	return interfaceQueries
}

func TestTheQuerierInterfaceIsGeneratedOnlyWhenThePresetAsksForIt(t *testing.T) {
	t.Parallel()

	for _, target := range featureTargets {
		t.Run(target.name, func(t *testing.T) {
			t.Parallel()

			defaults := generateFeatureProject(t, target, interfaceQueriesFor(target), seagull.DefaultPreset())
			require.NotContains(t, defaults, "querier_interface.go")

			chosen := seagull.DefaultPreset()
			chosen.Interface.Enabled = true
			generated := generateFeatureProject(t, target, interfaceQueriesFor(target), chosen)
			require.Contains(t, generated, "querier_interface.go")
			source := generated["querier_interface.go"]
			require.Contains(t, source, "// Code generated by sgl. DO NOT EDIT.")
			require.Contains(t, source, "type Querier interface {")
			require.Contains(t, source, "\tDeletePost(ctx context.Context, ")
			require.Contains(t, source, "\tListPosts(ctx context.Context) ([]ListPostsRow, error)\n")
			require.Contains(t, source, "\tSearchPosts() *SearchPostsBuilder\n")
			require.Contains(t, source, "var _ Querier = (*Queries)(nil)")
			require.NotContains(t, source, "WithTx")
			require.Equal(t, defaults["posts.sql.go"], generated["posts.sql.go"], "the interface leaves the query file alone")
			require.Equal(t, defaults["querier.go"], generated["querier.go"])
		})
	}
}

func TestTheQuerierInterfaceTakesItsConfiguredNameAndKeepsModelsClearOfIt(t *testing.T) {
	t.Parallel()

	target := featureTargets[0]
	target.migration += "CREATE TABLE store (id BIGINT PRIMARY KEY);\n"
	chosen := seagull.DefaultPreset()
	chosen.Interface = seagull.Interface{Enabled: true, Name: "Store"}

	generated := generateFeatureProject(t, target, interfaceQueries, chosen)

	require.Contains(t, generated["querier_interface.go"], "type Store interface {")
	require.Contains(t, generated["querier_interface.go"], "var _ Store = (*Queries)(nil)")
	require.Contains(t, generated["models.go"], "type Store2 struct {")
}

func TestAnInterfaceNameThePackageDeclaresIsRefused(t *testing.T) {
	t.Parallel()

	chosen := seagull.DefaultPreset()
	chosen.Interface = seagull.Interface{Enabled: true, Name: "Queries"}

	generator, err := seagull.New(featureTargets[0].engine(), seagull.WithPreset(chosen))

	require.ErrorIs(t, err, seagull.ErrInvalidConfig)
	require.ErrorContains(t, err, `the interface name "Queries" is a name the generated package already declares or imports`)
	require.Nil(t, generator)
}
