func TestDefaultPresetSpeaksSeagullVocabulary(t *testing.T) {
	t.Parallel()

	defaults := seagull.DefaultPreset()

	assert.Equal(t, "sgl", defaults.Directives.Canonical)
	assert.Equal(t, []string{"seagull"}, defaults.Directives.Aliases)
	assert.Len(t, defaults.Directives.Foreign, 1)
	assert.False(t, defaults.Directives.RequireCanonical)
	assert.Equal(t, "// Code generated by sgl. DO NOT EDIT.", defaults.Header)
	assert.Equal(t, "sgl", defaults.HelperPrefix)
	assert.Equal(t, "sgl", defaults.ErrorPrefix)
	assert.Equal(t, "SQL", defaults.SQLConstantSuffix)
	assert.Equal(t, seagull.QueryNames{Enabled: false, File: "query_names.go", Function: "QueryName"}, defaults.QueryNames)
	assert.Equal(t, seagull.TypeSlots{}, defaults.Types)
	require.NoError(t, defaults.Validate())
}

func TestDefaultPresetReturnsIndependentCopies(t *testing.T) {
	t.Parallel()

	first := seagull.DefaultPreset()
	first.Directives.Aliases[0] = "changed"

	assert.Equal(t, []string{"seagull"}, seagull.DefaultPreset().Directives.Aliases)
}

func TestPresetValidateRejectsUnusableSettings(t *testing.T) {
	t.Parallel()

	testCases := []struct {
		mutate     func(*seagull.Preset)
		wantPrefix bool
		name       string
	}{
		{name: "empty canonical prefix", wantPrefix: true, mutate: func(preset *seagull.Preset) { preset.Directives.Canonical = "" }},
		{name: "upper-case canonical prefix", wantPrefix: true, mutate: func(preset *seagull.Preset) { preset.Directives.Canonical = "Sgl" }},
		{name: "dotted alias", wantPrefix: true, mutate: func(preset *seagull.Preset) { preset.Directives.Aliases = []string{"sea.gull"} }},
		{name: "foreign prefix repeats the canonical one", wantPrefix: true, mutate: func(preset *seagull.Preset) { preset.Directives.Foreign = []string{"sgl"} }},
		{name: "duplicate alias", wantPrefix: true, mutate: func(preset *seagull.Preset) { preset.Directives.Aliases = []string{"seagull", "seagull"} }},
		{name: "overlong prefix", wantPrefix: true, mutate: func(preset *seagull.Preset) { preset.Directives.Canonical = "abcdefghijklmnopqrstuvwxyz0123456" }},
		{name: "helper prefix not an identifier start", wantPrefix: true, mutate: func(preset *seagull.Preset) { preset.HelperPrefix = "1sgl" }},
		{name: "error prefix with a format verb", wantPrefix: true, mutate: func(preset *seagull.Preset) { preset.ErrorPrefix = "sgl%d" }},
		{name: "header without the generated marker", wantPrefix: false, mutate: func(preset *seagull.Preset) { preset.Header = "// generated" }},
		{name: "header with trailing text", wantPrefix: false, mutate: func(preset *seagull.Preset) { preset.Header = "// Code generated by sgl. DO NOT EDIT. Really." }},
		{name: "query-names file outside the package", wantPrefix: false, mutate: func(preset *seagull.Preset) {
			preset.QueryNames = seagull.QueryNames{Enabled: true, File: "../names.go", Function: "QueryName"}
		}},
		{name: "query-names file is a test file", wantPrefix: false, mutate: func(preset *seagull.Preset) {
			preset.QueryNames = seagull.QueryNames{Enabled: true, File: "names_test.go", Function: "QueryName"}
		}},
		{name: "query-names function not an identifier", wantPrefix: false, mutate: func(preset *seagull.Preset) {
			preset.QueryNames = seagull.QueryNames{Enabled: true, File: "names.go", Function: "Query Name"}
		}},
	}

	for _, testCase := range testCases {
		t.Run(testCase.name, func(t *testing.T) {
			t.Parallel()

			candidate := seagull.DefaultPreset()
			testCase.mutate(&candidate)
			err := candidate.Validate()

			require.ErrorIs(t, err, seagull.ErrInvalidConfig)
			if testCase.wantPrefix {
				assert.ErrorIs(t, err, seagull.ErrInvalidPrefix)
			} else {
				assert.NotErrorIs(t, err, seagull.ErrInvalidPrefix)
			}
		})
	}
}

func TestPresetValidateIgnoresDisabledQueryNames(t *testing.T) {
	t.Parallel()

	candidate := seagull.DefaultPreset()
	candidate.QueryNames = seagull.QueryNames{Enabled: false, File: "", Function: ""}

	assert.NoError(t, candidate.Validate())
}
