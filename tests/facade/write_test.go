func generateTasks(t *testing.T) *seagull.Result {
	t.Helper()
	result, err := mustGenerator(t).Generate(t.Context(), tasksInput)
	require.NoError(t, err)
	require.NoError(t, result.Err())
	return result
}

func TestWriteFilesWritesAndPrunes(t *testing.T) {
	t.Parallel()

	directory := filepath.Join(t.TempDir(), "store")
	result := generateTasks(t)
	require.NoError(t, seagull.WriteFiles(directory, result))
	for _, file := range result.Files {
		if len(file.Content) > 0 {
			assert.FileExists(t, filepath.Join(directory, file.Name))
		}
	}

	stale := filepath.Join(directory, "dropped.sql.go")
	handwritten := filepath.Join(directory, "extra.go")
	legacy := filepath.Join(directory, "legacy.sql.go")
	require.NoError(t, os.WriteFile(stale, []byte(result.Header+"\n\npackage store\n"), 0o600))
	require.NoError(t, os.WriteFile(handwritten, []byte("package store\n"), 0o600))
	require.NoError(t, os.WriteFile(legacy, []byte("// Code generated by old. DO NOT EDIT.\n\npackage store\n"), 0o600))

	require.NoError(t, seagull.WriteFiles(directory, result, seagull.WithLegacyHeaders("// Code generated by old. DO NOT EDIT.")))
	assert.NoFileExists(t, stale)
	assert.NoFileExists(t, legacy)
	assert.FileExists(t, handwritten)
}

func TestWriteFilesOptions(t *testing.T) {
	t.Parallel()

	directory := t.TempDir()
	result := generateTasks(t)
	stale := filepath.Join(directory, "dropped.sql.go")
	require.NoError(t, os.WriteFile(stale, []byte(result.Header+"\n\npackage store\n"), 0o600))

	require.NoError(t, seagull.WriteFiles(directory, result, seagull.WithPrune(false)))
	assert.FileExists(t, stale, "pruning is off")

	require.NoError(t, seagull.WriteFiles(directory, result, seagull.WithHeader("// Code generated by acme. DO NOT EDIT.")))
	assert.FileExists(t, stale, "only files with the chosen header are pruned")

	require.NoError(t, seagull.WriteFiles(directory, result))
	assert.NoFileExists(t, stale)

	if runtime.GOOS != "windows" {
		require.NoError(t, seagull.WriteFiles(directory, result, seagull.WithPermissions(0o600)))
		info, err := os.Stat(filepath.Join(directory, "models.go"))
		require.NoError(t, err)
		assert.Equal(t, os.FileMode(0o600), info.Mode().Perm())
	}
}

func TestWriteFilesRefusesUnusableResults(t *testing.T) {
	t.Parallel()

	directory := t.TempDir()
	require.ErrorIs(t, seagull.WriteFiles(directory, nil), seagull.ErrInvalidConfig)
	require.ErrorIs(t, seagull.WriteFiles("", &seagull.Result{}), seagull.ErrInvalidConfig)
	require.ErrorIs(t, seagull.WriteFiles(directory, &seagull.Result{}, nil), seagull.ErrInvalidConfig)
	require.ErrorIs(t, seagull.WriteFiles(directory, &seagull.Result{}, seagull.WithPrune(false), nil), seagull.ErrInvalidConfig)

	bad := &seagull.Result{Files: []emit.GeneratedFile{{Name: "../escape.go", Content: []byte("x")}}}
	require.ErrorIs(t, seagull.WriteFiles(directory, bad), seagull.ErrInvalidConfig)

	project := tasksProject()
	project["db/queries/broken.sql"] = &fstest.MapFile{Data: []byte("-- sgl.query(name: Broken, command: invalid)\nSELECT id FROM tasks;\n")}
	generator, err := seagull.New(dialect_engine_sqlite.New())
	require.NoError(t, err)
	failed, err := generator.Generate(t.Context(), seagull.Input{
		Package: "store", Migrations: project, MigrationDir: "db/migrations", QueryDir: "db/queries",
	})
	require.NoError(t, err)

	existing := filepath.Join(directory, "models.go")
	require.NoError(t, os.WriteFile(existing, []byte(failed.Header+"\n\npackage store\n"), 0o600))
	require.ErrorIs(t, seagull.WriteFiles(directory, failed), seagull.ErrDiagnostics)
	assert.FileExists(t, existing, "a failed result must never prune")
}

func TestFormatDirectives(t *testing.T) {
	t.Parallel()

	tests := []struct {
		name      string
		source    string
		canonical string
		aliases   []string
		want      string
	}{
		{
			name:      "alias rewritten and spacing normalised",
			source:    "-- seagull.query(GetUser ,one)\nSELECT  id FROM users WHERE id = ?;\n",
			canonical: "sgl",
			aliases:   []string{"seagull"},
			want:      "-- sgl.query(GetUser, one)\nSELECT  id FROM users WHERE id = ?;\n",
		},
		{
			name:      "rewrite to a custom canonical prefix",
			source:    "-- sgl.query(A, one)\n-- $1 as sgl.param(id)\nSELECT 1;\n",
			canonical: "acme",
			aliases:   []string{"sgl", "seagull"},
			want:      "-- acme.query(A, one)\n-- $1 as acme.param(id)\nSELECT 1;\n",
		},
		{
			name:      "unknown prefixes are left alone",
			source:    "-- other.query( A ,one)\n",
			canonical: "sgl",
			want:      "-- other.query( A ,one)\n",
		},
	}
	for _, testCase := range tests {
		t.Run(testCase.name, func(t *testing.T) {
			t.Parallel()

			formatted, err := seagull.FormatDirectives([]byte(testCase.source), testCase.canonical, testCase.aliases...)
			require.NoError(t, err)
			assert.Equal(t, testCase.want, string(formatted))

			again, err := seagull.FormatDirectives(formatted, testCase.canonical, testCase.aliases...)
			require.NoError(t, err)
			assert.Equal(t, string(formatted), string(again), "formatting must be idempotent")
		})
	}
}

func TestFormatDirectivesRejectsBadPrefixes(t *testing.T) {
	t.Parallel()

	_, err := seagull.FormatDirectives(nil, "Sgl")
	require.ErrorIs(t, err, seagull.ErrInvalidPrefix)

	_, err = seagull.FormatDirectives(nil, "sgl", "seagull", "sgl")
	require.ErrorIs(t, err, seagull.ErrInvalidPrefix)
	assert.ErrorIs(t, err, seagull.ErrInvalidConfig)
}

func TestFormatDirectivesForReadsTheFileAsTheDialectWritesSQL(t *testing.T) {
	t.Parallel()

	tests := []struct {
		name        string
		source      string
		wantDialect string
		wantNeutral string
	}{
		{
			name:        "a directive-like line inside a backslash-escaped string is untouched",
			source:      "-- seagull.query(Note, one)\nSELECT 'it\\'s\n-- seagull.query(  X ,one)\n';\n",
			wantDialect: "-- sgl.query(Note, one)\nSELECT 'it\\'s\n-- seagull.query(  X ,one)\n';\n",
			wantNeutral: "-- sgl.query(Note, one)\nSELECT 'it\\'s\n-- sgl.query(X, one)\n';\n",
		},
		{
			name:        "a double dash without a space is not a comment, so not a directive",
			source:      "--seagull.query(X, one)\n",
			wantDialect: "--seagull.query(X, one)\n",
			wantNeutral: "-- sgl.query(X, one)\n",
		},
	}
	for _, testCase := range tests {
		t.Run(testCase.name, func(t *testing.T) {
			t.Parallel()

			formatted, err := seagull.FormatDirectivesFor(dialect_engine_mysql.New(), []byte(testCase.source), "sgl", "seagull")
			require.NoError(t, err)
			assert.Equal(t, testCase.wantDialect, string(formatted))
			again, err := seagull.FormatDirectivesFor(dialect_engine_mysql.New(), formatted, "sgl", "seagull")
			require.NoError(t, err)
			assert.Equal(t, string(formatted), string(again), "formatting must be idempotent")

			neutral, err := seagull.FormatDirectives([]byte(testCase.source), "sgl", "seagull")
			require.NoError(t, err)
			assert.Equal(t, testCase.wantNeutral, string(neutral), "the neutral rules read the file differently")
		})
	}
}

func TestFormatDirectivesForRejectsWhatItCannotUse(t *testing.T) {
	t.Parallel()

	_, err := seagull.FormatDirectivesFor(dialect.Dialect{}, nil, "sgl")
	require.ErrorIs(t, err, seagull.ErrInvalidConfig)

	_, err = seagull.FormatDirectivesFor(dialect_engine_sqlite.New(), nil, "Sgl")
	require.ErrorIs(t, err, seagull.ErrInvalidPrefix)

	_, err = seagull.FormatDirectivesFor(fakedialect.InfoPanics(dialect_engine_sqlite.New(), "no info"), nil, "sgl")
	require.ErrorIs(t, err, seagull.ErrPanic)
}
