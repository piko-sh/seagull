// WriteFiles writes a generation result's files into directory, creating it when missing.
// Each file is replaced atomically through a sandbox rooted at the directory, so a file
// name can never escape it.
//
// By default it then prunes: it removes every file in the directory whose first line is
// the result's header, or a legacy header, and that the result no longer contains, such
// as the file of a deleted query. Hand-written files, and files generated by other tools,
// are never removed.
//
// A result with error-severity diagnostics holds no files, so writing it would prune
// every generated file; WriteFiles refuses it and returns Result.Err instead. A partial
// result, generated under WithSkipFailingQueries, holds every query's files but those of
// the queries left out, and is written; the caller still reads Result.Err for the errors.
//
// Takes directory (string) which is the output directory.
// Takes result (*Result) which is the outcome of Generate.
// Takes options (...WriteOption) which configure pruning, headers and permissions.
//
// Returns error which is the result's *DiagnosticsError, wraps ErrInvalidConfig for a nil
// result, a nil option, an empty directory or a bad file name, or reports a failed write
// or prune.
func WriteFiles(directory string, result *Result, options ...WriteOption) error {
	return app.WriteFiles(directory, result, options...)
}

// WithPrune sets whether WriteFiles removes stale generated files. It is on by default.
//
// Takes enabled (bool) which is false to leave stale files in place.
//
// Returns WriteOption which sets pruning.
func WithPrune(enabled bool) WriteOption {
	return app.WithPrune(enabled)
}

// WithHeader sets the header that marks a file as generated when pruning. The default is
// the header of the preset that produced the result (Result.Header).
//
// Takes header (string) which is the generated-file header line.
//
// Returns WriteOption which sets the header.
func WithHeader(header string) WriteOption {
	return app.WithHeader(header)
}

// WithLegacyHeaders adds earlier generated-file headers whose files are pruned too, so a
// change of preset or header does not strand the files the old header marked.
//
// Takes headers (...string) which are appended to any added before.
//
// Returns WriteOption which adds the headers.
func WithLegacyHeaders(headers ...string) WriteOption {
	return app.WithLegacyHeaders(headers...)
}

// WithPermissions sets the permission of written files. The default is 0644.
//
// Takes permissions (fs.FileMode) which is the file permission; zero keeps the default.
//
// Returns WriteOption which sets the permission.
func WithPermissions(permissions fs.FileMode) WriteOption {
	return app.WithPermissions(permissions)
}

// FormatDirectives rewrites the directives of a SQL file into their canonical form,
// reading the file with neutral lexical rules, for a caller that has no dialect at hand;
// FormatDirectivesFor reads it as a dialect writes SQL, as the sgl fmt command does.
//
// A directive written with an alias prefix is rewritten to the canonical prefix, and the
// spacing inside directive comment lines is normalised: one space after the comment
// opener, single spaces between tokens, none inside brackets or before a comma, and one
// after a comma. Continuation lines of a multi-line directive keep their indentation. SQL
// bodies, prose comments, quoted directive values and text after a directive's closing
// parenthesis are never changed, and line endings are preserved. Formatting is
// idempotent. The neutral rules read '...' and "..." quotes in which a doubled quote
// stands for one, `...` identifiers, $$...$$ and $tag$...$tag$ bodies, and -- and /* */
// comments.
//
// Takes source ([]byte) which is the SQL file content.
// Takes canonical (string) which is the canonical directive prefix, such as sgl.
// Takes aliases (...string) which are the prefixes to rewrite to canonical, such as
// seagull.
//
// Returns []byte which is the formatted content.
// Returns error which wraps ErrInvalidPrefix when a prefix has the wrong shape or
// repeats.
func FormatDirectives(source []byte, canonical string, aliases ...string) ([]byte, error) {
	return app.FormatDirectives(source, canonical, aliases...)
}

// FormatDirectivesFor formats SQL directives using the dialect's lexical rules.
//
// Text inside quoted values or block comments is preserved, and only the dialect's line
// comments can contain directives.
//
// Takes engine (dialect.Dialect) which says how the file writes SQL, such as a
// dialect_engine_* provider's New from sdk/dialect.
// Takes source ([]byte) which is the SQL file content.
// Takes canonical (string) which is the canonical directive prefix, such as sgl.
// Takes aliases (...string) which are the prefixes to rewrite to canonical, such as
// seagull.
//
// Returns []byte which is the formatted content.
// Returns error which wraps ErrInvalidConfig for the zero Dialect or a dialect that does
// not describe itself fully, ErrInvalidPrefix when a prefix has the wrong shape or
// repeats, or ErrPanic when the dialect panicked describing itself.
func FormatDirectivesFor(engine dialect.Dialect, source []byte, canonical string, aliases ...string) ([]byte, error) {
	return app.FormatDirectivesFor(dialect.Unwrap(engine), source, canonical, aliases...)
}
